"""Build the island handover's national-spirit list and the debugger's cabinet reset."""

import argparse
from pathlib import Path

from tools.validators.validate_adiscord_division_templates import parse_clausewitz
from tools.validators.validate_adiscord_economy_ai import ASSISTANCE_IDEAS


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "common/scripted_effects/ADISCORD_debug_idea_catalogue.txt"


def render() -> bytes:
    # remove_ideas accepts literal tokens. This includes timed spirits granted
    # by foreign events, which cannot be inferred from NAM's history file.
    # A law slot can be declared once and receive additional choices in another file.
    ideas_by_slot = {}
    law_slots = set()
    for path in sorted((ROOT / "common/ideas").glob("*.txt")):
        for header in parse_clausewitz(path.read_text(encoding="utf-8-sig")):
            if header.key != "ideas":
                continue
            for slot in header.value:
                if not isinstance(slot.value, list):
                    continue
                if any(entry.key == "law" and entry.value == "yes" for entry in slot.value):
                    law_slots.add(slot.key)
                choices = ideas_by_slot.setdefault(slot.key, set())
                choices.update(entry.key for entry in slot.value if isinstance(entry.value, list))
    ideas = {token for slot, choices in ideas_by_slot.items() if slot not in law_slots for token in choices}
    spirits = ideas_by_slot["country"]
    debug_only = ideas.difference(spirits, ASSISTANCE_IDEAS)
    lines = [
        "# Generated by tools/builders/build_adiscord_idea_reset.py; do not edit.",
        "NAM_clear_mainland_national_spirits = {",
        "\tremove_ideas = {",
        *(f"\t\t{idea}" for idea in sorted(spirits)),
        "\t}",
        "}",
        "",
        "ADISCORD_debug_clear_country_ideas = {",
        "\tNAM_clear_mainland_national_spirits = yes",
        "\tremove_ideas = {",
        *(f"\t\t{idea}" for idea in sorted(debug_only)),
        "\t}",
        "\tclear_variable = ADISCORD_economy_ai_assistance_signature",
        "\tADISCORD_economy_refresh_ai_assistance = yes",
    ]
    people = parse_clausewitz((ROOT / "common/characters/NAM.txt").read_text(encoding="utf-8-sig"))
    for header in people:
        if header.key != "characters":
            continue
        for person in header.value:
            for role in person.value:
                if role.key != "advisor":
                    continue
                token = next(entry.value for entry in role.value if entry.key == "idea_token")
                lines.extend([
                    "\tif = {",
                    f"\t\tlimit = {{ {person.key} = {{ is_hired_as_advisor = yes }} }}",
                    f"\t\tdeactivate_advisor = {token}",
                    "\t}",
                ])
    lines.append("}")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    expected = render()
    if OUTPUT.is_file() and OUTPUT.read_bytes() == expected:
        return 0
    print(OUTPUT.relative_to(ROOT))
    if not args.apply:
        return 1
    OUTPUT.write_bytes(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
