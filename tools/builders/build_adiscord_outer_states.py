ROOT = repository_root()
STATE_DIR = ROOT / "history" / "states"
LOCALISATION = ROOT / "localisation" / "russian" / "state_names_l_russian.yml"
VICTORY_POINT_LOCALISATION = ROOT / "localisation" / "russian" / "victory_points_l_russian.yml"
GENERATED_MARKER = "# Generated by tools/build_adiscord_outer_states.py"
CLIMATE_MARKER = "# adiscord_climate_region = "
FIRST_STATE_ID = 331
WESTERN_SOURCE = ROOT / "tools/data/adiscord_western_states.json"


@cache
def western_source() -> dict[str, object]:
    return json.loads(WESTERN_SOURCE.read_text(encoding="utf-8"))


def northern_states(defined_provinces: dict[int, str]) -> list[PlannedState]:
    # Country capitals, settlements and borders depend on stable shell IDs.
    # Carved MON provinces join their parent shells once the map defines them.
    source = ROOT / "tools/data/adiscord_northern_state_shells.json"
    shells = json.loads(source.read_text(encoding="utf-8"))
    if set(map(int, shells)) != EXPECTED_STATES:
        raise ValueError("northern state shells must cover every northern country state")
    additions = mon_planned_provinces(load_mon_geography(), defined_provinces)
    return [
        PlannedState(
            int(state_id), "right", set(row["provinces"]) | additions.get(int(state_id), set()),
            row["climate"], row["name"],
        )
        for state_id, row in shells.items()
    ]


def western_states() -> list[PlannedState]:
    return [
        PlannedState(
            int(state_id), "left", set(row["provinces"]), row["climate"], row["name"]
        )
        for state_id, row in western_source()["states"].items()
        if 474 <= int(state_id) <= 550
    ]


@dataclass(frozen=True)
class ProvinceData:
    province_id: int
    x: float
    y: float
    height: float
    pixels: int
    terrain: str
    coastal: bool


@dataclass
class PlannedState:
    state_id: int
    landmass: str
    provinces: set[int]
    climate_region: str
    name: str


def state_path(state_id: int) -> Path:
    matches = sorted(STATE_DIR.glob(f"{state_id}-*.txt"))
    if len(matches) != 1:
        raise RuntimeError(f"state {state_id}: expected one file, found {len(matches)}")
    return matches[0]


def parse_state(path: Path) -> tuple[int, set[int], str]:
    source = path.read_text(encoding="utf-8-sig", errors="strict")
    state_match = re.search(r"\bid\s*=\s*(\d+)", source)
    province_match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", source, re.DOTALL)
    if not state_match or not province_match:
        raise RuntimeError(f"{path.relative_to(ROOT)}: missing id or provinces block")
    return (
        int(state_match.group(1)),
        {int(value) for value in re.findall(r"\d+", province_match.group(1))},
        source,
    )


def load_source_pool() -> tuple[set[int], set[int], str, list[Path]]:
    outer_path = state_path(23)
    _state_id, outer_provinces, outer_source = parse_state(outer_path)
    generated_paths: list[Path] = []
    generated_provinces: set[int] = set()
    for path in sorted(STATE_DIR.glob("*.txt")):
        source = path.read_text(encoding="utf-8-sig", errors="strict")
        if not source.startswith(GENERATED_MARKER):
            continue
        state_id, provinces, _source = parse_state(path)
        if str(state_id) in western_source().get("source_partitions", {}):
            provinces = set(western_source()["source_partitions"][str(state_id)]["provinces"])
        if state_id < FIRST_STATE_ID:
            raise RuntimeError(
                f"generated marker is not allowed on legacy state {state_id}"
            )
        overlap = generated_provinces & provinces
        if overlap:
            raise RuntimeError(
                f"generated states duplicate provinces {sorted(overlap)[:20]}"
            )
        generated_provinces.update(provinces)
        generated_paths.append(path)
    overlap = outer_provinces & generated_provinces
    if overlap:
        raise RuntimeError(
            f"state 23 overlaps generated states at provinces {sorted(overlap)[:20]}"
        )
    return (
        outer_provinces | generated_provinces,
        outer_provinces,
        outer_source,
        generated_paths,
    )


def load_definition_details() -> tuple[dict[int, str], dict[int, bool]]:
    terrain: dict[int, str] = {}
    coastal: dict[int, bool] = {}
    for line in (
        (ROOT / "map" / "definition.csv").read_text(encoding="utf-8-sig").splitlines()
    ):
        fields = line.split(";")
        if len(fields) < 7 or not fields[0].isdigit():
            continue
        province_id = int(fields[0])
        terrain[province_id] = fields[6]
        coastal[province_id] = fields[5].lower() == "true"
    return terrain, coastal


def load_pixel_areas(color_to_province: dict[int, int]) -> dict[int, int]:
    with Image.open(ROOT / "map" / "provinces.bmp") as source:
        image = source.convert("RGB")
        colors = image.getcolors(maxcolors=image.width * image.height)
    if colors is None:
        raise RuntimeError("could not enumerate province colours")
    areas: dict[int, int] = {}
    for count, (red, green, blue) in colors:
        color = (red << 16) | (green << 8) | blue
        province_id = color_to_province.get(color)
        if province_id is None:
            raise RuntimeError(
                f"provinces.bmp uses undefined colour {red};{green};{blue}"
            )
        areas[province_id] = count
    return areas


def build_province_data(
    province_types: dict[int, str], color_to_province: dict[int, int]
) -> dict[int, ProvinceData]:
    positions = load_province_positions()
    areas = load_pixel_areas(color_to_province)
    terrain, coastal = load_definition_details()
    data: dict[int, ProvinceData] = {}
    for province_id, province_type in province_types.items():
        if province_type != "land":
            continue
        if province_id not in positions or province_id not in areas:
            raise RuntimeError(
                f"land province {province_id} lacks a map position or pixel area"
            )
        x, height, z = positions[province_id]
        data[province_id] = ProvinceData(
            province_id=province_id,
            x=x,
            y=2048.0 - z,
            height=height,
            pixels=areas[province_id],
            terrain=terrain.get(province_id, "plains"),
            coastal=coastal.get(province_id, False),
        )
    return data


def component_center(
    component: set[int], data: dict[int, ProvinceData]
) -> tuple[float, float]:
    total = sum(data[province_id].pixels for province_id in component)
    return (
        sum(data[province_id].x * data[province_id].pixels for province_id in component)
        / total,
        sum(data[province_id].y * data[province_id].pixels for province_id in component)
        / total,
    )


def select_landmasses(
    pool: set[int], adjacency: dict[int, set[int]], data: dict[int, ProvinceData]
) -> tuple[set[int], set[int], list[set[int]]]:
    land_pool = set(pool) & set(data)
    components = connected_components(land_pool, adjacency)

    left_candidates = [
        component
        for component in components
        if len(component) >= 5000 and component_center(component, data)[0] < 2900
    ]
    if len(left_candidates) != 1:
        raise RuntimeError(
            f"expected one coarse left-continent component, found {len(left_candidates)}"
        )
    left = left_candidates[0]

    right_components: list[set[int]] = []
    for component in components:
        center_x, center_y = component_center(component, data)
        if component is left:
            continue
        if len(component) >= 300 and 2900 <= center_x < 4800 and center_y < 1200:
            right_components.append(component)
            continue
        # Nearby islands belong to the northern right-continent archipelagos.
        if len(component) < 300 and 2800 <= center_x < 4700 and center_y < 1100:
            right_components.append(component)

    right = set().union(*right_components) if right_components else set()
    if len(right) < 2500:
        raise RuntimeError(
            f"right-continent selection is unexpectedly small: {len(right)} provinces"
        )
    return left, right, right_components


def cluster_statistics(
    provinces: set[int], data: dict[int, ProvinceData]
) -> dict[str, object]:
    total_pixels = sum(data[p].pixels for p in provinces)
    x = sum(data[p].x * data[p].pixels for p in provinces) / total_pixels
    y = sum(data[p].y * data[p].pixels for p in provinces) / total_pixels
    average_height = (
        sum(data[p].height * data[p].pixels for p in provinces) / total_pixels
    )
    terrain_pixels: Counter[str] = Counter()
    coastal_pixels = 0
    for province_id in provinces:
        province = data[province_id]
        terrain_pixels[province.terrain] += province.pixels
        if province.coastal:
            coastal_pixels += province.pixels
    dominant = terrain_pixels.most_common(1)[0][0]
    highland_share = (
        sum(terrain_pixels[name] for name in ("hills", "mountain")) / total_pixels
    )
    wet_share = sum(terrain_pixels[name] for name in ("forest", "marsh")) / total_pixels
    return {
        "pixels": total_pixels,
        "x": x,
        "y": y,
        "height": average_height,
        "dominant": dominant,
        "highland_share": highland_share,
        "wet_share": wet_share,
        "coastal_share": coastal_pixels / total_pixels,
    }


def format_provinces(provinces: set[int], indent: str = "\t\t", width: int = 16) -> str:
    values = sorted(provinces)
    return "\n".join(
        indent + " ".join(str(value) for value in values[start : start + width])
        for start in range(0, len(values), width)
    )


def render_state(state: PlannedState, data: dict[int, ProvinceData]) -> str:
    if state.landmass == "left":
        row = western_source()["states"][str(state.state_id)]
        return render_western_state(state, row)
    stats = cluster_statistics(state.provinces, data)
    category = (
        "wasteland"
        if float(stats["y"]) < 300 or float(stats["highland_share"]) >= 0.70
        else "rural"
    )
    return (
        f"{GENERATED_MARKER}\n"
        f"{CLIMATE_MARKER}{state.climate_region}\n"
        "state = {\n"
        f"\tid = {state.state_id}\n"
        f'\tname = "STATE_{state.state_id}"\n'
        "\tmanpower = 1\n"
        f"\tstate_category = {category}\n"
        "\tprovinces = {\n"
        f"{format_provinces(state.provinces)}\n"
        "\t}\n"
        "\tbuildings_max_level_factor = 1.000\n"
        "\tlocal_supplies = 0.0\n"
        "}\n"
    )


def render_western_state(state: PlannedState, row: dict[str, object]) -> str:
    owner = row["owner"]
    marker = GENERATED_MARKER
    strategic_marker = ""
    if state.state_id >= 551:
        marker = "# Generated by tools/build_adiscord_remainder_states.py"
        strategic_marker = f"# adiscord_strategic_name = {state.name}\n"
    elif state.state_id == 77:
        marker = "# Generated by tools/builders/build_adiscord_outer_states.py (western manifest)"
    # Western countries are geographic placeholders. Population and industry
    # remain unbalanced until their own campaign content is authored; a state
    # with a "settlement" entry carries that population, industry and deposits,
    # and its island towns supply the victory points and harbours.
    # The manifest keeps the surveyed geometry; islets raised from the sea and
    # island districts are appended from their tables as the last rows.
    settlement = row.get("settlement")
    towns = [town for town in ISLAND_TOWNS if town["state"] == state.state_id]
    if towns and not settlement:
        raise RuntimeError(f"state {state.state_id}: island towns need a settlement entry")
    resources = ""
    history = ""
    if settlement:
        if settlement.get("resources"):
            deposits = "".join(
                f"\t\t{resource} = {amount}\n" for resource, amount in settlement["resources"].items()
            )
            resources = f"\tresources = {{\n{deposits}\t}}\n"
        points = "".join(
            f"\t\tvictory_points = {{ {town['province']} {town['town']['value']} }}\n" for town in towns
        )
        buildings = "".join(
            f"\t\t\t{building} = {level}\n" for building, level in settlement["buildings"].items()
        )
        harbours = "".join(
            f"\t\t\t{town['province']} = {{ naval_base = {town['town']['harbour']} }}\n"
            for town in towns
            if "harbour" in town["town"]
        )
        history = f"{points}\t\tbuildings = {{\n{buildings}{harbours}\t\t}}\n"
    rendered = (
        f"{marker}\n"
        f"{CLIMATE_MARKER}{state.climate_region}\n"
        f"{strategic_marker}"
        "state = {\n"
        f"\tid = {state.state_id}\n"
        f'\tname = "STATE_{state.state_id}"\n'
        f"\tmanpower = {settlement['population'] if settlement else 1}\n"
        f"\tstate_category = {settlement['category'] if settlement else 'wasteland' if owner == 'RSV' else 'rural'}\n"
        f"{resources}"
        "\thistory = {\n"
        f"\t\towner = {owner}\n"
        f"\t\tadd_core_of = {owner}\n"
        f"{history}"
        "\t}\n"
        "\tprovinces = {\n"
        f"{format_provinces(state.provinces)}\n"
        "\t}\n"
        "\tbuildings_max_level_factor = 1.000\n"
        f"\tlocal_supplies = {settlement['local_supplies'] if settlement else 0.0:.1f}\n"
        "}\n"
    )
    rendered = with_raised_island_provinces(rendered, state.state_id)
    return with_island_districts(rendered, state.state_id)


def western_outputs() -> dict[Path, str]:
    outputs = {}
    manifest = western_source()
    for state_id, row in manifest["states"].items():
        state = PlannedState(
            int(state_id), "left", set(row["provinces"]), row["climate"], row["name"]
        )
        path = ROOT / manifest["source_partitions"][state_id]["file"]
        outputs[path] = render_western_state(state, row)
    for row in manifest.get("donors", {}).values():
        path = ROOT / row["file"]
        outputs[path] = replace_outer_provinces(
            path.read_text(encoding="utf-8"), set(row["provinces"])
        )
    return outputs


def render_western_id(state_id: int) -> str:
    row = western_source()["states"][str(state_id)]
    state = PlannedState(
        state_id, "left", set(row["provinces"]), row["climate"], row["name"]
    )
    return render_western_state(state, row)


def check_western_outputs() -> list[str]:
    issues = [
        f"{path.relative_to(ROOT)}: western state differs from its source"
        for path, expected in western_outputs().items()
        if not path.exists() or path.read_text(encoding="utf-8") != expected
    ]
    names = dict(
        re.findall(
            r'^\s*STATE_(\d+)\s*:\s*(?:0\s*)?"([^"\r\n]*)"',
            LOCALISATION.read_text(encoding="utf-8-sig"),
            re.MULTILINE,
        )
    )
    for state_id, row in western_source()["states"].items():
        if names.get(state_id) != row["name"]:
            issues.append(f"STATE_{state_id}: western name differs from its source")
    towns = dict(
        re.findall(
            r'^\s*VICTORY_POINTS_(\d+)\s*:\s*(?:0\s*)?"([^"\r\n]*)"',
            VICTORY_POINT_LOCALISATION.read_text(encoding="utf-8-sig"),
            re.MULTILINE,
        )
    )
    for town in western_island_towns():
        if towns.get(str(town["province"])) != town["town"]["name"]:
            issues.append(f"VICTORY_POINTS_{town['province']}: island town name differs from its source")
    return issues


def western_island_towns() -> list[dict[str, object]]:
    return [town for town in ISLAND_TOWNS if str(town["state"]) in western_source()["states"]]


def apply_western_states() -> None:
    outputs = western_outputs()
    existing = set().union(*(parse_state(path)[1] for path in outputs))
    proposed_rows = [set(row["provinces"]) for row in western_source()["states"].values()]
    proposed_rows.extend(
        set(row["provinces"]) for row in western_source().get("donors", {}).values()
    )
    proposed_rows.extend(
        set(raised_island_provinces(int(state_id))) for state_id in western_source()["states"]
    )
    proposed_rows.extend(
        set(island_district_provinces(int(state_id))) for state_id in western_source()["states"]
    )
    proposed = set().union(*proposed_rows)
    if existing != proposed or sum(map(len, proposed_rows)) != len(proposed):
        raise RuntimeError("western province coverage must remain exact and unique")
    for path, expected in outputs.items():
        path.write_text(expected, encoding="utf-8", newline="\n")
    synchronize_western_localisation()
    mismatches = synchronize_buildings(ROOT, apply=True)
    state_ids = set(map(int, western_source()["states"])) | set(
        map(int, western_source().get("donors", {}))
    )
    added = ensure_state_spawn_positions(ROOT, state_ids)
    print(
        f"Applied {len(western_source()['states'])} western states; synchronized {len(mismatches)} "
        f"building assignments and added {added} construction anchors."
    )


def synchronize_western_localisation() -> None:
    source = LOCALISATION.read_text(encoding="utf-8-sig")
    for state_id, row in western_source()["states"].items():
        name = row["name"]
        source, count = re.subn(
            rf'(?m)^(\s*STATE_{state_id}\s*:\s*(?:0\s*)?)"[^"\r\n]*"',
            lambda match: match[1] + '"' + name + '"',
            source,
        )
        if count != 1:
            raise RuntimeError(f"expected one STATE_{state_id}, found {count}")
    LOCALISATION.write_text(source, encoding="utf-8-sig", newline="\n")
    towns = western_island_towns()
    if towns:
        source = VICTORY_POINT_LOCALISATION.read_text(encoding="utf-8-sig")
        for town in towns:
            source = replace_localisation_value(
                source, f"VICTORY_POINTS_{town['province']}", town["town"]["name"]
            )
        VICTORY_POINT_LOCALISATION.write_text(source, encoding="utf-8-sig", newline="\n")


def replace_outer_provinces(source: str, provinces: set[int]) -> str:
    match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", source, re.DOTALL)
    if not match:
        raise RuntimeError("state 23: missing provinces block")
    replacement = (
        "provinces={\n" + format_provinces(provinces, indent="\t\t", width=24) + "\n\t}"
    )
    return source[: match.start()] + replacement + source[match.end() :]


def validate_plan(
    planned: list[PlannedState], source_pool: set[int], right: set[int]
) -> None:
    expected_west = set().union(*(state.provinces for state in western_states()))
    expected = expected_west | right
    assigned: set[int] = set()
    for state in planned:
        if not state.provinces:
            raise RuntimeError(f"state {state.state_id} is empty")
        overlap = assigned & state.provinces
        if overlap:
            raise RuntimeError(f"new states duplicate provinces {sorted(overlap)[:20]}")
        assigned.update(state.provinces)
    if assigned != expected:
        raise RuntimeError(
            f"planned coverage mismatch: missing {len(expected-assigned)}, unexpected {len(assigned-expected)}"
        )
    if not assigned <= source_pool | expected_west:
        raise RuntimeError(
            "planned states use provinces outside state 23/generated source pool"
        )


def print_summary(planned: list[PlannedState], data: dict[int, ProvinceData]) -> None:
    by_landmass = Counter(state.landmass for state in planned)
    by_climate = Counter(state.climate_region for state in planned)
    print(f"Planned {len(planned)} states: {dict(sorted(by_landmass.items()))}")
    print("Climate groups:")
    for climate, count in sorted(by_climate.items()):
        print(f"- {climate}: {count}")
    for landmass in ("right", "left"):
        rows = [
            cluster_statistics(state.provinces, data)
            | {"provinces": len(state.provinces)}
            for state in planned
            if state.landmass == landmass
        ]
        province_counts = sorted(int(row["provinces"]) for row in rows)
        pixel_counts = sorted(int(row["pixels"]) for row in rows)
        if rows:
            middle = len(rows) // 2
            print(
                f"{landmass}: provinces median={province_counts[middle]}, range={province_counts[0]}..{province_counts[-1]}; "
                f"pixels median={pixel_counts[middle]}, range={pixel_counts[0]}..{pixel_counts[-1]}"
            )


def apply_plan(
    planned: list[PlannedState],
    data: dict[int, ProvinceData],
    original_outer: set[int],
    outer_source: str,
    generated_paths: list[Path],
) -> None:
    generated_provinces = set().union(*(state.provinces for state in planned))
    remaining_outer = (
        original_outer
        | set().union(*(parse_state(path)[1] for path in generated_paths))
    ) - generated_provinces
    remaining_outer -= set().union(*(
        set(row["provinces"]) for row in western_source()["states"].values()
    ))
    if not remaining_outer:
        raise RuntimeError("state 23 would become empty")

    # All destructive targets are explicitly marked generated files inside the
    # state directory; legacy/manual state files are never removed.
    for path in generated_paths:
        path.unlink()
    state_path(23).write_text(
        replace_outer_provinces(outer_source, remaining_outer),
        encoding="utf-8",
        newline="\n",
    )
    for state in planned:
        path = STATE_DIR / f"{state.state_id}-outer-{state.landmass}.txt"
        path.write_text(render_state(state, data), encoding="utf-8", newline="\n")

    replace_generated_localisation_block(
        LOCALISATION,
        "tools.builders.build_adiscord_outer_states",
        {f"STATE_{state.state_id}": state.name for state in planned},
    )
    apply_western_states()
    print(
        f"Applied {len(planned)} generated state shells; state 23 now keeps {len(remaining_outer)} provinces."
    )
    print(
        "Run northern countries --apply, exclusion boundaries --apply, then northern countries --apply again."
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument(
        "--check",
        action="store_true",
        help="validate current generated outputs (default)",
    )
    actions.add_argument(
        "--apply",
        action="store_true",
        help="write generated state files and localisation",
    )
    parser.add_argument(
        "--english-localisation",
        action="store_true",
        help="check or apply only reviewed English names",
    )
    parser.add_argument(
        "--western-only",
        action="store_true",
        help="synchronize only the western mainland, islands and their boundary donors",
    )
    args = parser.parse_args()
    if args.english_localisation:
        from tools.lib.localisation import sync_builder_english_localisation

        return sync_builder_english_localisation(
            ROOT, "tools.builders.build_adiscord_outer_states", apply=args.apply
        )

    if args.western_only:
        if args.apply:
            apply_western_states()
            return 0
        issues = check_western_outputs()
        for issue in issues:
            print(issue)
        return int(bool(issues))

    if not args.apply:
        from tools.validators.validate_adiscord_outer_states import (
            main as validate_main,
        )

        return validate_main()

    source_pool, original_outer, outer_source, generated_paths = load_source_pool()
    province_types, color_to_province = load_province_definitions()
    data = build_province_data(province_types, color_to_province)
    adjacency = load_province_adjacency(province_types, color_to_province)
    _left, right, _components = select_landmasses(source_pool, adjacency, data)
    planned = northern_states(province_types) + western_states()
    validate_plan(planned, source_pool, right)
    print_summary(planned, data)
    apply_plan(planned, data, original_outer, outer_source, generated_paths)
    mismatches = synchronize_buildings(ROOT, apply=True)
    print(f"Synchronized {len(mismatches)} map-building state assignments.")
    return 0


