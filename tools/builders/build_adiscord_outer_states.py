def local_toponym_forms(root: str) -> tuple[str, str, str, str]:
    return root + "ский", root + "ская", root + "ское", root + "ские"


def assign_ids_and_metadata(
    clusters: list[tuple[str, set[int]]], data: dict[int, ProvinceData]
) -> list[PlannedState]:
    ordered = sorted(
        clusters,
        key=lambda item: (
            0 if item[0] == "right" else 1,
            cluster_statistics(item[1], data)["y"],
            cluster_statistics(item[1], data)["x"],
            min(item[1]),
        ),
    )
    statistics = [cluster_statistics(provinces, data) for _landmass, provinces in ordered]
    climate_keys = [
        climate_region(landmass, stats)
        for (landmass, _provinces), stats in zip(ordered, statistics)
    ]
    name_parts = [
        state_name_parts(climate_key, provinces, data)
        for (_landmass, provinces), climate_key in zip(ordered, climate_keys)
    ]
    base_names = [parts[0] for parts in name_parts]
    name_totals = Counter(base_names)
    local_toponym_index = 0
    planned: list[PlannedState] = []
    for index, ((landmass, provinces), stats, climate_key, parts) in enumerate(
        zip(ordered, statistics, climate_keys, name_parts)
    ):
        state_id = FIRST_STATE_ID + index
        base_name, gender, feature = parts
        if name_totals[base_name] == 1:
            name = base_name
        else:
            if local_toponym_index >= len(LOCAL_TOPONYM_ROOTS):
                raise RuntimeError("not enough local toponyms to disambiguate generated state names")
            forms = local_toponym_forms(LOCAL_TOPONYM_ROOTS[local_toponym_index])
            local_toponym_index += 1
            name = f"{forms[gender]} {feature}"
        planned.append(
            PlannedState(
                state_id=state_id,
                landmass=landmass,
                provinces=provinces,
                climate_region=climate_key,
                name=name,
            )
        )
    return planned


def format_provinces(provinces: set[int], indent: str = "\t\t", width: int = 16) -> str:
    values = sorted(provinces)
    return "\n".join(
        indent + " ".join(str(value) for value in values[start:start + width])
        for start in range(0, len(values), width)
    )


def render_state(state: PlannedState, data: dict[int, ProvinceData]) -> str:
    stats = cluster_statistics(state.provinces, data)
    category = "wasteland" if float(stats["y"]) < 300 or float(stats["highland_share"]) >= 0.70 else "rural"
    return (
        f"{GENERATED_MARKER}\n"
        f"{CLIMATE_MARKER}{state.climate_region}\n"
        "state = {\n"
        f"\tid = {state.state_id}\n"
        f'\tname = "STATE_{state.state_id}"\n'
        "\tmanpower = 1\n"
        f"\tstate_category = {category}\n"
        "\tprovinces = {\n"
        f"{format_provinces(state.provinces)}\n"
        "\t}\n"
        "\tbuildings_max_level_factor = 1.000\n"
        "\tlocal_supplies = 0.0\n"
        "}\n"
    )


def replace_outer_provinces(source: str, provinces: set[int]) -> str:
    match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", source, re.DOTALL)
    if not match:
        raise RuntimeError("state 23: missing provinces block")
    replacement = "provinces={\n" + format_provinces(provinces, indent="\t\t", width=24) + "\n\t}"
    return source[:match.start()] + replacement + source[match.end():]


def validate_plan(
    planned: list[PlannedState], source_pool: set[int], left: set[int], right: set[int]
) -> None:
    expected = left | right
    assigned: set[int] = set()
    for state in planned:
        if not state.provinces:
            raise RuntimeError(f"state {state.state_id} is empty")
        overlap = assigned & state.provinces
        if overlap:
            raise RuntimeError(f"new states duplicate provinces {sorted(overlap)[:20]}")
        assigned.update(state.provinces)
    if assigned != expected:
        raise RuntimeError(
            f"planned coverage mismatch: missing {len(expected-assigned)}, unexpected {len(assigned-expected)}"
        )
    if not assigned <= source_pool:
        raise RuntimeError("planned states use provinces outside state 23/generated source pool")


def print_summary(planned: list[PlannedState], data: dict[int, ProvinceData]) -> None:
    by_landmass = Counter(state.landmass for state in planned)
    by_climate = Counter(state.climate_region for state in planned)
    print(f"Planned {len(planned)} states: {dict(sorted(by_landmass.items()))}")
    print("Climate groups:")
    for climate, count in sorted(by_climate.items()):
        print(f"- {climate}: {count}")
    for landmass in ("right", "left"):
        rows = [cluster_statistics(state.provinces, data) | {"provinces": len(state.provinces)} for state in planned if state.landmass == landmass]
        province_counts = sorted(int(row["provinces"]) for row in rows)
        pixel_counts = sorted(int(row["pixels"]) for row in rows)
        if rows:
            middle = len(rows) // 2
            print(
                f"{landmass}: provinces median={province_counts[middle]}, range={province_counts[0]}..{province_counts[-1]}; "
                f"pixels median={pixel_counts[middle]}, range={pixel_counts[0]}..{pixel_counts[-1]}"
            )


def apply_plan(
    planned: list[PlannedState],
    data: dict[int, ProvinceData],
    original_outer: set[int],
    outer_source: str,
    generated_paths: list[Path],
) -> None:
    generated_provinces = set().union(*(state.provinces for state in planned))
    remaining_outer = (original_outer | set().union(*(parse_state(path)[1] for path in generated_paths))) - generated_provinces
    if not remaining_outer:
        raise RuntimeError("state 23 would become empty")

    # All destructive targets are explicitly marked generated files inside the
    # state directory; legacy/manual state files are never removed.
    for path in generated_paths:
        path.unlink()
    state_path(23).write_text(replace_outer_provinces(outer_source, remaining_outer), encoding="utf-8", newline="\n")
    for state in planned:
        path = STATE_DIR / f"{state.state_id}-outer-{state.landmass}.txt"
        path.write_text(render_state(state, data), encoding="utf-8", newline="\n")

    localisation = ["\ufeffl_russian:"]
    localisation.extend(f' STATE_{state.state_id}: "{state.name}"' for state in planned)
    LOCALISATION.write_text("\n".join(localisation) + "\n", encoding="utf-8", newline="\n")
    print(f"Applied {len(planned)} generated state shells; state 23 now keeps {len(remaining_outer)} provinces.")
    print("Run tools/build_adiscord_northern_countries.py --apply next to restore northern owners and balance data.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="write generated state files and localisation")
    args = parser.parse_args()

    source_pool, original_outer, outer_source, generated_paths = load_source_pool()
    province_types, color_to_province = load_province_definitions()
    data = build_province_data(province_types, color_to_province)
    adjacency = load_province_adjacency(province_types, color_to_province)
    left, right, right_components = select_landmasses(source_pool, adjacency, data)
    clusters = plan_clusters(left, right_components, adjacency, data)
    planned = assign_ids_and_metadata(clusters, data)
    validate_plan(planned, source_pool, left, right)
    print_summary(planned, data)
    if args.apply:
        apply_plan(planned, data, original_outer, outer_source, generated_paths)
        mismatches = synchronize_buildings(ROOT, apply=True)
        print(f"Synchronized {len(mismatches)} map-building state assignments.")
    else:
        print("Dry run only; pass --apply to write files.")


if __name__ == "__main__":
    main()
