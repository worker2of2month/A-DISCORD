#!/usr/bin/env python3
"""Build northern state shells and the authored western country partition.

The detailed southern/eastern state work (IDs 1-330) remains authoritative.
The northern shell manifest fixes province membership, names and climates.
The western manifest also supplies ownership. The northern-country builder
populates its shells before and after the Exclusion Zone boundary pass.

The split is deliberately asymmetric:

* the unfinished upper half of the right continent is medium-fine;
* the far north becomes progressively coarser;
* the main left continent and its islands follow their authored state partition;
* the separate far-eastern continent remains untouched.

Run without ``--apply`` for a read-only summary.  Generated state files are
idempotent: a later run first folds the marked files back into the source pool.
"""

