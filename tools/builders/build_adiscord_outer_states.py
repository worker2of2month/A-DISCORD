"""Cut the unfinished northern/eastern and western landmasses into state shells.

The detailed southern/eastern state work (IDs 1-330) remains authoritative.
This pass only removes provinces from the catch-all state 23, creates neutral
state shells, and records a climate key for the strategic-region builder.

The split is deliberately asymmetric:

* the unfinished upper half of the right continent is medium-fine;
* the far north becomes progressively coarser;
* the main left continent receives a coarse provisional split;
* the separate far-eastern continent and minor western islands are untouched.

Run without ``--apply`` for a read-only summary.  Generated state files are
idempotent: a later run first folds the marked files back into the source pool.
"""

