def load_states() -> dict[int, set[int]]:
    states: dict[int, set[int]] = {}
    for path in STATE_DIR.glob("*.txt"):
        text = path.read_text(encoding="utf-8-sig", errors="strict")
        state_match = re.search(r"\bid\s*=\s*(\d+)", text)
        province_match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", text, re.DOTALL)
        if not state_match or not province_match:
            continue
        state_id = int(state_match.group(1))
        if state_id in states:
            raise ValueError(f"duplicate state id {state_id}")
        states[state_id] = {int(value) for value in re.findall(r"\d+", province_match.group(1))}
    return states


