def build_state_adjacency(
    states: dict[int, set[int]], province_adjacency: dict[int, set[int]]
) -> dict[int, set[int]]:
    """Collapse physical province borders into a state-neighbour graph."""
    state_by_province = {
        province_id: state_id
        for state_id, provinces in states.items()
        for province_id in provinces
    }
    adjacency = {state_id: set() for state_id in states}
    for province_id, state_id in state_by_province.items():
        for neighbour in province_adjacency.get(province_id, set()):
            other_state = state_by_province.get(neighbour)
            if other_state is not None and other_state != state_id:
                adjacency[state_id].add(other_state)
    return adjacency


def _partition_connected_states(
    nodes: set[int],
    parts: int,
    adjacency: dict[int, set[int]],
    weights: dict[int, float],
    centers: dict[int, tuple[float, float]],
) -> list[set[int]]:
    """Split a connected state graph via cuts that keep both sides connected."""
    if parts <= 1:
        return [set(nodes)]
    if len(nodes) < parts:
        raise ValueError(f"cannot split {len(nodes)} states into {parts} connected parts")

    total_weight = sum(weights[node] for node in nodes)
    center_x = sum(centers[node][0] * weights[node] for node in nodes) / total_weight
    center_z = sum(centers[node][1] * weights[node] for node in nodes) / total_weight
    root = min(
        nodes,
        key=lambda node: (
            (centers[node][0] - center_x) ** 2 + (centers[node][1] - center_z) ** 2,
            node,
        ),
    )

    parent: dict[int, int | None] = {root: None}
    order: list[int] = []
    queue = deque((root,))
    while queue:
        node = queue.popleft()
        order.append(node)
        neighbours = sorted(
            adjacency[node] & nodes,
            key=lambda other: (
                (centers[other][0] - centers[node][0]) ** 2
                + (centers[other][1] - centers[node][1]) ** 2,
                other,
            ),
        )
        for neighbour in neighbours:
            if neighbour not in parent:
                parent[neighbour] = node
                queue.append(neighbour)
    if len(order) != len(nodes):
        raise ValueError("attempted to partition a disconnected state graph")

    subtrees = {node: {node} for node in nodes}
    subtree_weights = {node: weights[node] for node in nodes}
    for node in reversed(order[1:]):
        ancestor = parent[node]
        assert ancestor is not None
        subtrees[ancestor].update(subtrees[node])
        subtree_weights[ancestor] += subtree_weights[node]

    ideal_weight = total_weight / parts
    candidates: list[tuple[float, int, int, set[int]]] = []
    for branch_root in order[1:]:
        branch = subtrees[branch_root]
        remainder_size = len(nodes) - len(branch)
        minimum_branch_parts = max(1, parts - remainder_size)
        maximum_branch_parts = min(parts - 1, len(branch))
        for branch_parts in range(minimum_branch_parts, maximum_branch_parts + 1):
            branch_weight = subtree_weights[branch_root]
            remainder_parts = parts - branch_parts
            score = (
                abs(branch_weight - ideal_weight * branch_parts)
                + abs((total_weight - branch_weight) - ideal_weight * remainder_parts)
            ) / total_weight
            candidates.append((score, branch_root, branch_parts, branch))
    if not candidates:
        raise ValueError(f"no connected cut can split {len(nodes)} states into {parts} parts")

    _score, _branch_root, branch_parts, branch = min(
        candidates, key=lambda row: (row[0], row[1], row[2])
    )
    remainder = nodes - branch
    return (
        _partition_connected_states(branch, branch_parts, adjacency, weights, centers)
        + _partition_connected_states(remainder, parts - branch_parts, adjacency, weights, centers)
    )


def _roman(value: int) -> str:
    numerals = ((10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I"))
    result = ""
    for number, glyph in numerals:
        while value >= number:
            result += glyph
            value -= number
    return result


def load_generated_outer_regions() -> tuple[Region, ...]:
    generated_states: dict[int, set[int]] = {}
    climate_by_state: dict[int, str] = {}
    preferred_names: dict[int, str] = {}
    for path in STATE_DIR.glob("*.txt"):
        source = path.read_text(encoding="utf-8-sig", errors="strict")
        if not source.startswith((OUTER_STATE_MARKER, REMAINDER_STATE_MARKER)):
            continue
        state_match = re.search(r"\bid\s*=\s*(\d+)", source)
        climate_match = re.search(r"(?m)^# adiscord_climate_region = ([a-z_]+)\s*$", source)
        preferred_name_match = re.search(r"(?m)^# adiscord_strategic_name = (.+?)\s*$", source)
        province_match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", source, re.DOTALL)
        if not state_match or not climate_match or not province_match:
            raise ValueError(f"{path.name}: generated outer state lacks id, provinces, or climate marker")
        state_id = int(state_match.group(1))
        climate_key = climate_match.group(1)
        if climate_key not in OUTER_REGION_SPECS:
            raise ValueError(f"{path.name}: unknown outer climate key {climate_key}")
        generated_states[state_id] = {int(value) for value in re.findall(r"\d+", province_match.group(1))}
        climate_by_state[state_id] = climate_key
        if source.startswith(REMAINDER_STATE_MARKER):
            if not preferred_name_match:
                raise ValueError(f"{path.name}: remainder state lacks a strategic-name marker")
            preferred_names[state_id] = preferred_name_match.group(1).strip()

    if not generated_states:
        return ()

    province_types, color_to_province = load_province_definitions()
    physical_adjacency = load_province_adjacency(
        province_types, color_to_province, include_special_adjacencies=False
    )
    state_adjacency = build_state_adjacency(generated_states, physical_adjacency)
    province_positions = load_province_positions()
    province_weights = {state_id: len(provinces) for state_id, provinces in generated_states.items()}
    centers: dict[int, tuple[float, float]] = {}
    for state_id, provinces in generated_states.items():
        available = [province_positions[province_id] for province_id in provinces if province_id in province_positions]
        if not available:
            raise ValueError(f"generated state {state_id} has no map positions")
        centers[state_id] = (
            sum(position[0] for position in available) / len(available),
            sum(position[2] for position in available) / len(available),
        )

    cluster_rows: list[tuple[str, set[int], str]] = []
    climate_zones: dict[tuple[str, int], set[int]] = {}
    for state_id, climate_key in climate_by_state.items():
        landmass = climate_key.split("_", 1)[0]
        if landmass not in ("left", "right", "world"):
            raise ValueError(f"state {state_id}: cannot infer landmass from climate key {climate_key}")
        climate_zones.setdefault((landmass, OUTER_CLIMATE_BELTS[climate_key]), set()).add(state_id)

    for (landmass, belt), zone_states in sorted(climate_zones.items()):
        if landmass == "world":
            # Remainder shells are maximal physically connected components of
            # one latitude band, so they intentionally remain one region each.
            target_provinces = 1.0
        elif landmass == "left":
            target_provinces = (180.0, 180.0, 220.0, 420.0, 520.0)[belt]
        else:
            target_provinces = (220.0, 200.0, 220.0, 250.0)[belt]
        partition_weights = {
            state_id: (1.0 if landmass == "world" else province_weights[state_id] / target_provinces)
            for state_id in zone_states
        }

        for component in connected_components(zone_states, state_adjacency):
            part_count = min(
                len(component),
                max(1, math.ceil(sum(partition_weights[state_id] for state_id in component))),
            )
            clusters = _partition_connected_states(
                component, part_count, state_adjacency, partition_weights, centers
            )
            for cluster in clusters:
                climate_counts = Counter(
                    {
                        key: sum(
                            province_weights[state_id]
                            for state_id in cluster
                            if climate_by_state[state_id] == key
                        )
                        for key in OUTER_REGION_SPECS
                    }
                )
                climate_key = min(
                    climate_counts,
                    key=lambda key: (-climate_counts[key], key),
                )
                cluster_rows.append((landmass, cluster, climate_key))

    cluster_rows.sort(
        key=lambda row: (
            {"right": 0, "left": 1, "world": 2}[row[0]],
            -sum(centers[state_id][1] * province_weights[state_id] for state_id in row[1])
            / sum(province_weights[state_id] for state_id in row[1]),
            sum(centers[state_id][0] * province_weights[state_id] for state_id in row[1])
            / sum(province_weights[state_id] for state_id in row[1]),
            min(row[1]),
        )
    )
    region_centers = [
        (
            sum(centers[state_id][0] * province_weights[state_id] for state_id in cluster)
            / sum(province_weights[state_id] for state_id in cluster),
            sum(centers[state_id][1] * province_weights[state_id] for state_id in cluster)
            / sum(province_weights[state_id] for state_id in cluster),
        )
        for _landmass, cluster, _climate_key in cluster_rows
    ]
    base_names: list[str] = []
    for index, (landmass, cluster, climate_key) in enumerate(cluster_rows):
        if landmass == "world":
            if len(cluster) != 1:
                raise ValueError(f"world remainder region unexpectedly groups states {sorted(cluster)}")
            state_id = next(iter(cluster))
            try:
                base_names.append(preferred_names[state_id])
            except KeyError as exc:
                raise ValueError(f"world remainder state {state_id} lacks a preferred region name") from exc
        else:
            base_names.append(outer_region_name(climate_key, region_centers[index][0]))
    display_names = list(base_names)
    duplicate_groups: dict[str, list[int]] = {}
    for index, base_name in enumerate(base_names):
        duplicate_groups.setdefault(base_name, []).append(index)
    for base_name, indices in duplicate_groups.items():
        if len(indices) == 1:
            continue
        x_span = max(region_centers[index][0] for index in indices) - min(region_centers[index][0] for index in indices)
        z_span = max(region_centers[index][1] for index in indices) - min(region_centers[index][1] for index in indices)
        horizontal = x_span >= z_span
        qualifiers_by_count = HORIZONTAL_REGION_QUALIFIERS if horizontal else VERTICAL_REGION_QUALIFIERS
        if len(indices) not in qualifiers_by_count:
            raise ValueError(f"cannot geographically disambiguate {len(indices)} regions named {base_name}")
        ordered_indices = sorted(
            indices,
            key=(
                (lambda index: region_centers[index][0])
                if horizontal
                else (lambda index: -region_centers[index][1])
            ),
        )
        if cluster_rows[indices[0]][0] == "world":
            raise ValueError(f"duplicate remainder strategic name {base_name}")
        gender = outer_region_name_gender(cluster_rows[indices[0]][2])
        for index, qualifier in zip(ordered_indices, qualifiers_by_count[len(indices)]):
            display_names[index] = f"{qualifier[gender]} {base_name}"

    file_indices: Counter[str] = Counter()
    regions: list[Region] = []
    for region_id, ((_landmass, cluster, climate_key), base_name, display_name) in enumerate(
        zip(cluster_rows, base_names, display_names), 43
    ):
        slug, _old_name, climate = OUTER_REGION_SPECS[climate_key]
        file_indices[base_name] += 1
        file_suffix = "" if len(duplicate_groups[base_name]) == 1 else f"-{file_indices[base_name]}"
        regions.append(
            Region(
                region_id,
                slug + file_suffix,
                display_name,
                climate,
                tuple(sorted(cluster)),
            )
        )
    return tuple(regions)


REGIONS = (*BASE_REGIONS, *load_generated_outer_regions())


def format_provinces(provinces: set[int]) -> str:
    values = sorted(provinces)
    lines = []
    for start in range(0, len(values), 24):
        lines.append("\t\t" + " ".join(str(value) for value in values[start:start + 24]))
    return "\n".join(lines)


def format_weather(climate: str) -> str:
    lines = ["\tweather={"]
    for month, date_range in enumerate(MONTH_RANGES):
        low, high = TEMPERATURES[climate][month]
        clear, light, heavy, snow, blizzard, mud, sandstorm = phenomenon(climate, month)
        lines.extend((
            "\t\tperiod={",
            f"\t\t\tbetween={{ {date_range} }}",
            f"\t\t\ttemperature={{ {low:.1f} {high:.1f} }}",
            f"\t\t\tno_phenomenon={clear:.2f}",
            f"\t\t\train_light={light:.2f}",
            f"\t\t\train_heavy={heavy:.2f}",
            f"\t\t\tsnow={snow:.2f}",
            f"\t\t\tblizzard={blizzard:.2f}",
            f"\t\t\tarctic_water={arctic_water(climate, month):.2f}",
            f"\t\t\tmud={mud:.2f}",
            f"\t\t\tsandstorm={sandstorm:.2f}",
            f"\t\t\tmin_snow_level={minimum_snow_level(climate, month):.2f}",
            "\t\t}",
        ))
    lines.append("\t}")
    return "\n".join(lines)


def representative_positions(
    provinces: set[int],
    positions: dict[int, tuple[float, float, float]],
    adjacency: dict[int, set[int]] | None = None,
) -> list[tuple[float, float, float]]:
    available = [positions[province_id] for province_id in provinces if province_id in positions]
    if not available and adjacency is not None:
        # Non-state inland-water provinces have no unit-stack coordinates.
        # Place their weather marker on the immediately surrounding shore
        # instead of inventing a map coordinate or attaching distant land.
        shore = {
            neighbour
            for province_id in provinces
            for neighbour in adjacency.get(province_id, set())
            if neighbour in positions
        }
        available = [positions[province_id] for province_id in sorted(shore)]
    if not available:
        raise ValueError("strategic region has no unit-stack positions")
    if len(available) == 1:
        return available

    x_span = max(point[0] for point in available) - min(point[0] for point in available)
    z_span = max(point[2] for point in available) - min(point[2] for point in available)
    axis = 0 if x_span >= z_span else 2
    ordered = sorted(available, key=lambda point: point[axis])
    if len(available) < 24:
        return [ordered[len(ordered) // 2]]
    return [ordered[len(ordered) // 3], ordered[(2 * len(ordered)) // 3]]


def sea_region_id_for(position: tuple[float, float, float]) -> int:
    x, _height, z = position
    latitude_band = 0 if z >= 1600 else 1 if z >= 1250 else 2 if z >= 900 else 3 if z >= 550 else 4
    longitude_band = 0 if x < 1800 else 1 if x < 3800 else 2
    return SEA_REGION_GRID[latitude_band][longitude_band]


def validate_manifest(states: dict[int, set[int]]) -> None:
    assigned: dict[int, int] = {}
    for region in REGIONS:
        if region.climate not in TEMPERATURES:
            raise ValueError(f"region {region.region_id} uses unknown climate {region.climate}")
        for state_id in region.states:
            if state_id not in states:
                raise ValueError(f"region {region.region_id} references missing state {state_id}")
            if state_id in assigned:
                raise ValueError(f"state {state_id} is in regions {assigned[state_id]} and {region.region_id}")
            assigned[state_id] = region.region_id
    missing = sorted(set(states) - set(assigned))
    if missing:
        raise ValueError(f"states without a strategic region: {missing}")


def build() -> None:
    states = load_states()
    validate_manifest(states)
    province_types, color_to_province = load_province_definitions()
    non_sea = {province_id for province_id, province_type in province_types.items() if province_type != "sea"}
    sea = {province_id for province_id, province_type in province_types.items() if province_type == "sea"}
    state_provinces = set().union(*states.values())
    unknown = state_provinces - non_sea
    if unknown:
        raise ValueError(f"state provinces absent from non-sea definition rows: {sorted(unknown)}")

    for path in REGION_DIR.glob("*.txt"):
        text = path.read_text(encoding="utf-8-sig", errors="strict")
        if path.name in ("1-sea.txt", "2-land.txt") or text.startswith(GENERATED_MARKER):
            path.unlink()

    province_positions = load_province_positions()
    for province_id in sea:
        if province_id not in province_positions:
            raise ValueError(f"sea province {province_id} has no unit-stack position")

    adjacency = load_province_adjacency(province_types, color_to_province)
    sea_components = connected_components(sea, adjacency)
    if not sea_components:
        raise ValueError("map contains no sea provinces")
    main_ocean = sea_components[0]

    dedicated_union: set[int] = set()
    for region in DEDICATED_SEA_REGIONS:
        provinces = set(DEDICATED_SEA_PROVINCES[region.region_id])
        if provinces - sea:
            raise ValueError(
                f"dedicated sea region {region.region_id} contains non-sea provinces: {sorted(provinces - sea)}"
            )
        overlap = dedicated_union & provinces
        if overlap:
            raise ValueError(f"dedicated sea provinces assigned more than once: {sorted(overlap)}")
        if not provinces <= main_ocean:
            raise ValueError(
                f"dedicated sea region {region.region_id} must belong to the navigable ocean component"
            )
        if len(connected_components(provinces, adjacency)) != 1:
            raise ValueError(f"dedicated sea region {region.region_id} is not internally connected")
        dedicated_union.update(provinces)

    region_provinces: dict[int, set[int]] = {}
    land_region_by_province: dict[int, int] = {}
    for region in REGIONS:
        provinces = set().union(*(states[state_id] for state_id in region.states))
        if region.region_id == 2:
            provinces |= non_sea - state_provinces
        region_provinces[region.region_id] = provinces
        for province_id in provinces:
            land_region_by_province[province_id] = region.region_id

    for region_id, provinces in DEDICATED_SEA_PROVINCES.items():
        region_provinces[region_id] = set(provinces)

    # Inland lakes must belong to their surrounding land region. Combining them
    # with the ocean makes Clausewitz report a fractioned naval strategic region.
    for component in sea_components[1:]:
        neighbouring_land = Counter(
            land_region_by_province[neighbour]
            for province_id in component
            for neighbour in adjacency[province_id]
            if neighbour in land_region_by_province
        )
        if not neighbouring_land:
            raise ValueError(f"isolated sea component {sorted(component)} has no neighbouring land region")
        region_id = min(neighbouring_land, key=lambda candidate: (-neighbouring_land[candidate], candidate))
        region_provinces[region_id].update(component)

    # Partition the complete navigable ocean first, then cut the local basin out
    # of its macro region.  This keeps every unrelated ocean boundary stable.
    macro_partition = partition_connected_sea(main_ocean, adjacency, province_positions)
    for region_id, provinces in DEDICATED_SEA_PROVINCES.items():
        source_regions = {
            macro_region_id
            for macro_region_id, macro_provinces in macro_partition.items()
            if macro_provinces & set(provinces)
        }
        if len(source_regions) != 1:
            raise ValueError(
                f"dedicated sea region {region_id} crosses macro-ocean boundaries: {sorted(source_regions)}"
            )
        macro_partition[next(iter(source_regions))].difference_update(provinces)
    region_provinces.update(macro_partition)

    sea_by_id = {region.region_id: region for region in ALL_SEA_REGIONS}
    for region_id, region in sorted(sea_by_id.items()):
        provinces = region_provinces.get(region_id, set())
        if not provinces:
            raise ValueError(f"sea strategic region {region_id} is empty")
        content = (
            f"{GENERATED_MARKER}\n"
            "strategic_region={\n"
            f"\tid={region.region_id}\n"
            f"\tname=\"STRATEGICREGION_{region.region_id}\"\n"
            "\tprovinces={\n"
            f"{format_provinces(provinces)}\n"
            "\t}\n"
            f"\tnaval_terrain={region.naval_terrain}\n"
            f"{format_weather(region.climate)}\n"
            "}\n"
        )
        path = REGION_DIR / f"{region.region_id}-{region.slug}.txt"
        path.write_text(content, encoding="utf-8", newline="\n")

    for region in REGIONS:
        provinces = region_provinces[region.region_id]
        content = (
            f"{GENERATED_MARKER}\n"
            "strategic_region={\n"
            f"\tid={region.region_id}\n"
            f"\tname=\"STRATEGICREGION_{region.region_id}\"\n"
            "\tprovinces={\n"
            f"{format_provinces(provinces)}\n"
            "\t}\n"
            f"{format_weather(region.climate)}\n"
            "}\n"
        )
        path = REGION_DIR / f"{region.region_id}-{region.slug}.txt"
        path.write_text(content, encoding="utf-8", newline="\n")

    LOCALISATION.parent.mkdir(parents=True, exist_ok=True)
    localisation_lines = ["\ufeffl_russian:"]
    for region in sorted((*ALL_SEA_REGIONS, *REGIONS), key=lambda item: item.region_id):
        localisation_lines.append(f' STRATEGICREGION_{region.region_id}: "{region.russian_name}"')
    LOCALISATION.write_text("\n".join(localisation_lines) + "\n", encoding="utf-8", newline="\n")

    weather_lines = []
    for region_id in sorted(region_provinces):
        size = "big" if len(region_provinces[region_id]) >= 100 else "small"
        for x, height, z in representative_positions(
            region_provinces[region_id], province_positions, adjacency
        ):
            weather_lines.append(f"{region_id};{x:.2f};{height:.2f};{z:.2f};{size}")
    WEATHER_POSITIONS.write_text("\n".join(weather_lines) + "\n", encoding="utf-8", newline="\n")

    print(f"Built {len(REGIONS)} land and {len(ALL_SEA_REGIONS)} sea strategic regions for {len(states)} states.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate A-Discord strategic regions and weather positions.")
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument("--check", action="store_true", help="validate current generated outputs (default)")
    actions.add_argument("--apply", action="store_true", help="write strategic regions, localisation and weather positions")
    args = parser.parse_args()
    if args.apply:
        build()
        return 0
    from tools.validators.validate_adiscord_strategic_regions import main as validate_main

    return validate_main()


