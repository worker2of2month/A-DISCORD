def load_province_adjacency(
    province_types: dict[int, str],
    color_to_province: dict[int, int],
    include_special_adjacencies: bool = True,
) -> dict[int, set[int]]:
    """Read physical borders and, optionally, special links into a province graph."""
    adjacency = {province_id: set() for province_id in province_types}
    with Image.open(ROOT / "map" / "provinces.bmp") as source:
        image = source.convert("RGB")
        width, height = image.size
        red, green, blue = (band.tobytes() for band in image.split())

    previous_row = [-1] * width
    for y in range(height):
        row_start = y * width
        first = -1
        left = -1
        for x in range(width):
            offset = row_start + x
            color = (red[offset] << 16) | (green[offset] << 8) | blue[offset]
            try:
                province_id = color_to_province[color]
            except KeyError as exc:
                raise ValueError(
                    f"provinces.bmp uses undefined color {color >> 16};{(color >> 8) & 255};{color & 255} at {x},{y}"
                ) from exc
            if x == 0:
                first = province_id
            elif province_id != left:
                adjacency[province_id].add(left)
                adjacency[left].add(province_id)
            above = previous_row[x]
            if above != -1 and province_id != above:
                adjacency[province_id].add(above)
                adjacency[above].add(province_id)
            previous_row[x] = province_id
            left = province_id

        # Clausewitz maps wrap horizontally, so the two map edges are adjacent.
        if first != left:
            adjacency[first].add(left)
            adjacency[left].add(first)

    adjacency_path = ROOT / "map" / "adjacencies.csv"
    if include_special_adjacencies and adjacency_path.exists():
        with adjacency_path.open(encoding="utf-8-sig", newline="") as handle:
            for row in csv.reader(handle, delimiter=";"):
                if len(row) < 2 or not row[0].isdigit() or not row[1].isdigit():
                    continue
                first, second = int(row[0]), int(row[1])
                if first in adjacency and second in adjacency:
                    adjacency[first].add(second)
                    adjacency[second].add(first)
    return adjacency


def connected_components(nodes: set[int], adjacency: dict[int, set[int]]) -> list[set[int]]:
    remaining = set(nodes)
    components: list[set[int]] = []
    while remaining:
        start = min(remaining)
        component = {start}
        queue = deque((start,))
        remaining.remove(start)
        while queue:
            province_id = queue.popleft()
            for neighbour in adjacency[province_id]:
                if neighbour in remaining:
                    remaining.remove(neighbour)
                    component.add(neighbour)
                    queue.append(neighbour)
        components.append(component)
    return sorted(components, key=lambda component: (-len(component), min(component)))


def partition_connected_sea(
    sea: set[int],
    adjacency: dict[int, set[int]],
    positions: dict[int, tuple[float, float, float]],
) -> dict[int, set[int]]:
    """Partition one connected ocean with a seeded BFS, preserving connectivity."""
    seeds: dict[int, int] = {}
    for sea_region in SEA_REGIONS:
        candidates = [
            province_id
            for province_id in sea
            if sea_region_id_for(positions[province_id]) == sea_region.region_id
        ]
        if not candidates:
            raise ValueError(f"sea strategic region {sea_region.region_id} has no seed candidates")
        center_x = sum(positions[province_id][0] for province_id in candidates) / len(candidates)
        center_z = sum(positions[province_id][2] for province_id in candidates) / len(candidates)
        seeds[sea_region.region_id] = min(
            candidates,
            key=lambda province_id: (
                (positions[province_id][0] - center_x) ** 2 + (positions[province_id][2] - center_z) ** 2,
                province_id,
            ),
        )

    assignments = {province_id: region_id for region_id, province_id in seeds.items()}
    queue = deque(seeds[region_id] for region_id in sorted(seeds))
    while queue:
        province_id = queue.popleft()
        region_id = assignments[province_id]
        for neighbour in sorted(adjacency[province_id]):
            if neighbour in sea and neighbour not in assignments:
                assignments[neighbour] = region_id
                queue.append(neighbour)
    if set(assignments) != sea:
        raise ValueError("main ocean component could not be fully partitioned")

    partition = {region.region_id: set() for region in SEA_REGIONS}
    for province_id, region_id in assignments.items():
        partition[region_id].add(province_id)
    return partition


