def render_flag(
    tag: str, colors: tuple[tuple[int, int, int], ...], style: int
) -> Image.Image:
    if tag == "MON":
        with Image.open(ROOT / "tools/assets/source/MON_flag.png") as source:
            return source.convert("RGBA")
    if tag in MONTAR_SUCCESSORS:
        return render_montar_successor_flag(tag)
    if tag in {"AUR", "LYS", "LMN", "RLY", "SFR", "PRR", "FLR"}:
        with Image.open(ROOT / "tools/assets/source/country_flags" / f"{tag}.png") as source:
            return source.convert("RGBA")
    width, height = 82, 52
    primary, secondary, accent = colors
    image = Image.new("RGBA", (width, height), primary + (255,))
    draw = ImageDraw.Draw(image)
    if tag == "VEL":
        draw.rectangle((0, 17, width, 34), fill=accent + (255,))
        for x in (16, 39, 62):
            draw.rectangle((x, 21, x + 5, 30), fill=secondary + (255,))
        return image
    if tag == "HON":
        draw.rectangle((0, 17, width, 34), fill=secondary + (255,))
        draw.rectangle((0, 34, width, height), fill=accent + (255,))
        draw.ellipse((34, 18, 48, 32), fill=(211, 174, 67, 255))
        return image
    mode = style % 6
    if mode == 0:
        draw.rectangle(
            (0, height // 3, width, 2 * height // 3), fill=secondary + (255,)
        )
        draw.rectangle((0, 2 * height // 3, width, height), fill=accent + (255,))
    elif mode == 1:
        draw.rectangle((width // 3, 0, 2 * width // 3, height), fill=secondary + (255,))
        draw.rectangle((2 * width // 3, 0, width, height), fill=accent + (255,))
    elif mode == 2:
        draw.rectangle((0, 20, width, 31), fill=secondary + (255,))
        draw.rectangle((24, 0, 36, height), fill=secondary + (255,))
        draw.rectangle((27, 0, 33, height), fill=accent + (255,))
    elif mode == 3:
        draw.polygon(((0, 0), (width, 0), (0, height)), fill=secondary + (255,))
        draw.polygon(((width, 0), (width, height), (0, height)), fill=accent + (255,))
    elif mode == 4:
        draw.polygon(((0, 0), (33, height // 2), (0, height)), fill=secondary + (255,))
        draw.polygon(((0, 8), (23, height // 2), (0, height - 8)), fill=accent + (255,))
    else:
        draw.line((0, 0, width, height), fill=secondary + (255,), width=10)
        draw.line((0, height, width, 0), fill=secondary + (255,), width=10)
        draw.ellipse((34, 19, 48, 33), fill=accent + (255,))
    return image


def write_flags(
    tags: tuple[str, ...] | None = None, *, apply: bool = True
) -> list[Path]:
    sizes = (
        (FLAG_DIR, (82, 52)),
        (FLAG_DIR / "medium", (41, 26)),
        (FLAG_DIR / "small", (10, 7)),
    )
    changed = []
    for tag in COUNTRIES if tags is None else tags:
        country = COUNTRIES[tag]
        base = render_flag(tag, country["colors"], FLAG_STYLES[tag])
        for directory, size in sizes:
            image = (
                base
                if size == base.size
                else base.resize(size, Image.Resampling.LANCZOS)
            )
            buffer = BytesIO()
            image.save(buffer, format="TGA")
            path = directory / f"{tag}.tga"
            data = buffer.getvalue()
            if not path.exists() or path.read_bytes() != data:
                changed.append(path)
                if apply:
                    directory.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(data)
    return changed


def add_victory_point_name(
    localisation: dict[str, str], province_id: int, name: str
) -> None:
    key = f"VICTORY_POINTS_{province_id}"
    if localisation.setdefault(key, name) != name:
        raise RuntimeError(f"{key} is named both {localisation[key]} and {name}")


def victory_point_localisation(
    principal_provinces: dict[int, int],
    mon_points: tuple[tuple[int, int, int, str], ...],
) -> dict[str, str]:
    """Preserve the catalogue order, with Vald before the regional settlement table."""
    localisation: dict[str, str] = {}
    for tag, country in COUNTRIES.items():
        if tag == "ARK":
            add_victory_point_name(localisation, principal_provinces[460], "Вальд")
            for state_id, province_id, _value, name in mon_points:
                if state_id in MONTAR_STATES:
                    add_victory_point_name(localisation, province_id, name)
            continue
        if tag in MONTAR_SUCCESSORS:
            continue
        add_country_victory_point_names(
            localisation, country, principal_provinces, mon_points
        )
    return localisation


def add_country_victory_point_names(
    localisation: dict[str, str],
    country: dict[str, object],
    principal_provinces: dict[int, int],
    points: tuple[tuple[int, int, int, str], ...],
) -> None:
    """Name a country's settlement points, then the manifest centres of its other states."""
    states = {int(state_id) for state_id in country["states"]}
    settled: set[int] = set()
    for state_id, province_id, _value, name in points:
        if state_id in states:
            add_victory_point_name(localisation, province_id, name)
            settled.add(state_id)
    capital = int(country["capital"])
    if capital not in settled:
        add_victory_point_name(
            localisation, principal_provinces[capital], str(country["capital_name"])
        )
    for state_id, name, _value in country.get("secondary_vps", ()):
        if int(state_id) not in settled:
            add_victory_point_name(
                localisation, principal_provinces[int(state_id)], str(name)
            )


def generated_block_entries(
    source: str, marker: str = BUILDER_MODULE
) -> list[tuple[str, str]] | None:
    begin = f" # BEGIN GENERATED: {marker}\n"
    end = f" # END GENERATED: {marker}"
    if source.count(begin) != 1 or source.count(end) != 1:
        return None
    block = source.split(begin, 1)[1].split(end, 1)[0]
    return re.findall(r'(?m)^ ([A-Za-z0-9_.-]+): "([^"\n]*)"$', block)


def english_specification(catalogue: dict[str, object]) -> dict[str, object]:
    source = VP_LOCALISATION.relative_to(ROOT).as_posix()
    matches = [
        specification
        for specification in catalogue[BUILDER_MODULE]
        if specification["source"] == source
    ]
    if len(matches) != 1:
        raise RuntimeError(f"expected one English VP name review for {source}")
    return matches[0]


def promote_village_names(
    specification: dict[str, object], localisation: dict[str, str]
) -> list[str]:
    """Key reviewed village names by the provinces the MON plan has chosen.

    Village names are reviewed before their provinces exist, so they wait in
    ``village_names`` keyed by the Russian name.
    """
    reviewed = specification["entries"]
    village_names = specification.get("village_names", {})
    promoted = []
    for key, russian in localisation.items():
        if key not in reviewed and russian in village_names:
            reviewed[key] = {"russian": russian, "english": village_names[russian]}
            promoted.append(key)
    return promoted


def english_name_gaps(
    specification: dict[str, object], localisation: dict[str, str]
) -> list[str]:
    reviewed = specification["entries"]
    village_names = specification.get("village_names", {})
    gaps = []
    for key, russian in localisation.items():
        review = reviewed.get(key)
        if review is None:
            pending = village_names.get(russian)
            hint = f"; reviewed village name {pending!r} is promoted by --apply" if pending else ""
            gaps.append(f"{key} ({russian}) has no English pair{hint}")
        elif review["russian"] != russian:
            gaps.append(f"{key} is reviewed as {review['russian']}, rendered as {russian}")
    for key in sorted(set(reviewed) - set(localisation)):
        gaps.append(f"{key} is reviewed but no longer rendered")
    return gaps


def sync_english_localisation(*, apply: bool) -> int:
    from tools.lib.localisation import sync_builder_english_localisation

    _profiles, principal_provinces = build_profiles()
    localisation = victory_point_localisation(
        principal_provinces, load_mon_settlement_points()
    )
    catalogue = json.loads(ENGLISH_NAMES.read_text(encoding="utf-8"))
    specification = english_specification(catalogue)
    promoted = promote_village_names(specification, localisation) if apply else []
    gaps = english_name_gaps(specification, localisation)
    if gaps:
        print(f"English victory-point names need review ({len(gaps)}):")
        for gap in gaps:
            print(f"- {gap}")
        return 1
    russian = VP_LOCALISATION.read_text(encoding="utf-8-sig")
    if generated_block_entries(russian) != list(localisation.items()):
        print(
            f"{VP_LOCALISATION.relative_to(ROOT)} is stale: run --apply before syncing the English names."
        )
        return 1
    if promoted:
        ENGLISH_NAMES.write_bytes(
            (json.dumps(catalogue, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
        )
        print(f"Promoted reviewed village names: {', '.join(promoted)}")
    return sync_builder_english_localisation(ROOT, BUILDER_MODULE, apply=apply)


def apply() -> None:
    profiles, principal_provinces = build_profiles()
    for state_id, profile in sorted(profiles.items()):
        state_path(state_id).write_text(
            render_state(state_id, profile), encoding="utf-8", newline="\n"
        )
    update_oobs(principal_provinces, apply=True)
    replace_generated_localisation_block(
        VP_LOCALISATION,
        BUILDER_MODULE,
        victory_point_localisation(principal_provinces, load_mon_settlement_points()),
    )
    write_flags()
    print(
        f"Applied {len(profiles)} populated northern states, the northern OOBs and {len(COUNTRIES) * 3} flags."
    )


def print_summary() -> None:
    profiles, _principal = build_profiles()
    for tag, country in COUNTRIES.items():
        states = [profiles[int(state_id)] for state_id in country["states"]]
        population = sum(int(state["population"]) for state in states)
        civilian = sum(int(state["civilian"]) for state in states)
        military = sum(int(state["military"]) for state in states)
        resources = Counter()
        for state in states:
            resources.update(state["resources"])
        print(
            f"{tag}: states={len(states)} population={population:,} factories={civilian}+{military} "
            f"divisions={country['divisions']} resources={dict(sorted(resources.items()))}"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument(
        "--check",
        action="store_true",
        help="validate current generated outputs (default)",
    )
    actions.add_argument(
        "--apply",
        action="store_true",
        help="write states, OOBs, victory-point localisation and flags",
    )
    parser.add_argument(
        "--states-only",
        nargs="+",
        type=int,
        choices=sorted(EXPECTED_STATES),
        metavar="STATE_ID",
        help="check or apply only the selected state histories",
    )
    parser.add_argument(
        "--flags-only",
        nargs="+",
        choices=tuple(COUNTRIES),
        metavar="TAG",
        help="check or apply only the named countries' flag textures",
    )
    parser.add_argument(
        "--english-localisation",
        action="store_true",
        help="check or apply only reviewed English names",
    )
    parser.add_argument(
        "--oobs-only",
        action="store_true",
        help="check or apply only the generated northern orders of battle",
    )
    args = parser.parse_args()
    if args.oobs_only:
        if args.flags_only or args.states_only or args.english_localisation:
            parser.error("--oobs-only cannot be combined with other output selections")
        _, provinces = build_profiles()
        changed = update_oobs(provinces, apply=args.apply)
        print(f"Selected OOB changes: {changed}")
        return int(bool(changed) and not args.apply)
    if args.states_only:
        if args.flags_only or args.english_localisation:
            parser.error("--states-only cannot be combined with other output selections")
        profiles, _principal = build_profiles()
        changed = []
        for state_id in sorted(set(args.states_only)):
            path = state_path(state_id)
            output = render_state(state_id, profiles[state_id]).encode("utf-8")
            if path.read_bytes() != output:
                changed.append(state_id)
                if args.apply:
                    path.write_bytes(output)
        print(f"Selected state changes: {changed}")
        return int(bool(changed) and not args.apply)
    if args.flags_only:
        if args.english_localisation:
            parser.error("--flags-only cannot be combined with --english-localisation")
        changed = write_flags(tuple(args.flags_only), apply=args.apply)
        for path in changed:
            print(("Updated: " if args.apply else "Drift: ") + str(path.relative_to(ROOT)))
        if not changed:
            print("Selected northern flags are current.")
        return int(bool(changed) and not args.apply)
    if args.english_localisation:
        return sync_english_localisation(apply=args.apply)
    if args.apply:
        print_summary()
        apply()
        return 0
    from tools.validators.validate_adiscord_northern_countries import (
        main as validate_main,
    )

    return validate_main()


