def state_path(state_id: int) -> Path:
    matches = sorted(STATE_DIR.glob(f"{state_id}-outer-right.txt"))
    if len(matches) != 1:
        raise RuntimeError(
            f"state {state_id}: expected one outer-right file, found {len(matches)}"
        )
    return matches[0]


def parse_state(path: Path) -> tuple[int, tuple[int, ...], str]:
    source = path.read_text(encoding="utf-8-sig", errors="strict")
    state_match = re.search(r"\bid\s*=\s*(\d+)", source)
    province_match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", source, re.DOTALL)
    climate_match = re.search(r"# adiscord_climate_region = (\S+)", source)
    if (
        not source.startswith(OUTER_MARKER)
        or not state_match
        or not province_match
        or not climate_match
    ):
        raise RuntimeError(
            f"{path.relative_to(ROOT)} is not a generated outer-right state"
        )
    return (
        int(state_match.group(1)),
        tuple(int(value) for value in re.findall(r"\d+", province_match.group(1))),
        climate_match.group(1),
    )


def load_definition() -> (
    tuple[dict[tuple[int, int, int], int], dict[int, dict[str, object]]]
):
    color_to_province: dict[tuple[int, int, int], int] = {}
    details: dict[int, dict[str, object]] = {}
    for line in (
        (ROOT / "map" / "definition.csv").read_text(encoding="utf-8-sig").splitlines()
    ):
        fields = line.split(";")
        if len(fields) < 7 or not fields[0].isdigit():
            continue
        province_id = int(fields[0])
        color_to_province[(int(fields[1]), int(fields[2]), int(fields[3]))] = (
            province_id
        )
        details[province_id] = {
            "type": fields[4],
            "coastal": fields[5].lower() == "true",
            "terrain": fields[6],
        }
    return color_to_province, details


def load_pixel_areas(
    color_to_province: dict[tuple[int, int, int], int],
) -> dict[int, int]:
    with Image.open(ROOT / "map" / "provinces.bmp") as source:
        colors = source.convert("RGB").getcolors(maxcolors=source.width * source.height)
    if colors is None:
        raise RuntimeError("could not enumerate provinces.bmp colours")
    areas: dict[int, int] = {}
    for count, color in colors:
        province_id = color_to_province.get(color)
        if province_id is None:
            raise RuntimeError(f"provinces.bmp contains undefined colour {color}")
        areas[province_id] = count
    return areas


def load_positions() -> dict[int, tuple[float, float]]:
    positions: dict[int, tuple[float, float]] = {}
    for line in (
        (ROOT / "map" / "unitstacks.txt").read_text(encoding="utf-8-sig").splitlines()
    ):
        fields = line.strip().split(";")
        if len(fields) >= 5 and fields[0].isdigit() and fields[1] == "0":
            positions.setdefault(
                int(fields[0]), (float(fields[2]), 2048.0 - float(fields[4]))
            )
    return positions


def largest_remainder(total: int, weights: dict[int, float]) -> dict[int, int]:
    weight_total = sum(weights.values())
    raw = {key: total * weight / weight_total for key, weight in weights.items()}
    result = {key: int(value) for key, value in raw.items()}
    remaining = total - sum(result.values())
    for key in sorted(weights, key=lambda item: (-(raw[item] - result[item]), item))[
        :remaining
    ]:
        result[key] += 1
    return result


def distribute_levels(
    total: int, ordered_states: list[int], per_state_cap: int
) -> dict[int, int]:
    result = {state_id: 0 for state_id in ordered_states}
    cursor = 0
    while total > 0:
        state_id = ordered_states[cursor % len(ordered_states)]
        cursor += 1
        if result[state_id] >= per_state_cap:
            if all(level >= per_state_cap for level in result.values()):
                per_state_cap += 1
            continue
        result[state_id] += 1
        total -= 1
    return result


def format_provinces(provinces: tuple[int, ...], width: int = 16) -> str:
    values = sorted(provinces)
    return "\n".join(
        "\t\t" + " ".join(str(value) for value in values[start : start + width])
        for start in range(0, len(values), width)
    )


def load_mon_geography(path: Path = MON_GEOGRAPHY) -> dict[str, object]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("schema") != 1:
        raise RuntimeError(f"{path.name}: unsupported MON geography schema")
    return payload


def geography_scope_states(geography: dict[str, object]) -> frozenset[int]:
    """Return every state of the eastern geography: the MON region and the neighbour regions.

    The scope is keyed by state id, never by the current owner of a state. A
    region of Stage 3 or later joins once the geography planner has recorded
    its stage, so its settlements name planned provinces.
    """
    planned = {int(stage["stage"]) for stage in geography.get("stages", ())}
    states = set(geography.get("states", ()))
    for region in geography.get("regions", {}).values():
        stage = int(region.get("stage", 2))
        if stage <= 2 or stage in planned:
            states.update(region["states"])
    return frozenset(int(state_id) for state_id in states)


def mon_plan_stages(geography: dict[str, object]) -> tuple[tuple[dict[str, object], ...], ...]:
    """Return the recorded province plans in map-apply order: Stage 1, Stage 2, then each later stage."""
    return tuple(tuple(stage.get("provinces", ())) for stage in east_stages(geography))


def mon_plan_stage_numbers(geography: dict[str, object]) -> tuple[int, ...]:
    """Return the stage number of each recorded plan, in the order of `mon_plan_stages`."""
    return tuple(int(stage.get("stage", number)) for number, stage in enumerate(east_stages(geography), start=1))


def mon_planned_ids(geography: dict[str, object]) -> dict[int, int]:
    """Map every planned province of all stages to the state that receives it."""
    states: dict[int, int] = {}
    for stage in mon_plan_stages(geography):
        for entry in stage:
            if entry["kind"] not in GEOGRAPHY_PLANNED_KINDS:
                raise RuntimeError(f"planned province {entry['province']}: unknown kind {entry['kind']!r}")
            province_id = int(entry["province"])
            if province_id in states:
                raise RuntimeError(f"planned province {province_id} appears in more than one plan entry")
            states[province_id] = int(entry["state"])
    return states


def mon_planned_entries(
    geography: dict[str, object], defined_provinces: object
) -> tuple[dict[str, object], ...]:
    """Return the plan entries of every stage the map already defines.

    A plan is recorded before its map apply, so its ids are absent from
    definition.csv until then; the state lists keep their shells meanwhile.
    Each stage reaches the map as a whole.
    """
    mon_planned_ids(geography)
    defined = set(defined_provinces)
    entries: list[dict[str, object]] = []
    for number, stage in zip(mon_plan_stage_numbers(geography), mon_plan_stages(geography)):
        planned = {int(entry["province"]) for entry in stage}
        present = planned & defined
        if not present:
            continue
        if present != planned:
            missing = sorted(planned - present)
            raise RuntimeError(
                f"Stage {number} province plan is only partly on the map: "
                f"{len(missing)} missing from {missing[0]}"
            )
        entries.extend(stage)
    return tuple(entries)


def mon_planned_provinces(
    geography: dict[str, object], defined_provinces: object
) -> dict[int, frozenset[int]]:
    """Return the planned provinces by state once the map defines them."""
    by_state: dict[int, set[int]] = {}
    for entry in mon_planned_entries(geography, defined_provinces):
        by_state.setdefault(int(entry["state"]), set()).add(int(entry["province"]))
    return {state_id: frozenset(provinces) for state_id, provinces in by_state.items()}


def mon_planned_roots(entries: tuple[dict[str, object], ...]) -> dict[int, int]:
    """Map each planned province to the original map province it was cut from.

    A Stage 2 part may be cut from a planned remainder, so parents are followed
    until they leave the plan.
    """
    parents = {int(entry["province"]): int(entry["parent"]) for entry in entries}
    roots: dict[int, int] = {}
    for province_id in parents:
        root = parents[province_id]
        visited = {province_id}
        while root in parents:
            if root in visited:
                raise RuntimeError(f"planned province {province_id} has a cyclic parent chain")
            visited.add(root)
            root = parents[root]
        roots[province_id] = root
    return roots


def mon_city_parents(geography: dict[str, object]) -> dict[int, int]:
    """Return the principal city of each state: MON cities and the neighbour cities.

    The MON second cities of Stage 2 hold victory points but are never principal.
    A settlement of kind `adopt` makes an existing city province principal.
    """
    parents: dict[int, int] = {}
    tables = (
        geography["settlements"],
        *(region["settlements"] for region in geography.get("regions", {}).values()),
    )
    for table in tables:
        for entry in table:
            if entry["kind"] not in ("city", "adopt"):
                continue
            # A city or adoption the planner has not resolved names no province yet.
            province = entry.get("parent") if entry["kind"] == "city" else entry.get("province")
            if province is None:
                continue
            state_id = int(entry["state"])
            if state_id in parents:
                raise RuntimeError(f"geography state {state_id} has more than one principal city")
            parents[state_id] = int(province)
    return parents


def mon_settlement_points(
    geography: dict[str, object],
) -> tuple[tuple[int, int, int, str], ...]:
    """Return (state, province, value, name) of every settlement with a victory point.

    Cities come first, then villages and towns. Each group follows the tables
    in order: MON cities and villages, MON second cities, then each neighbour
    region. A village without a chosen province has no victory point yet;
    districts never hold one.
    """
    tables = (
        geography["settlements"],
        geography.get("stage2", {}).get("settlements", ()),
        *(region["settlements"] for region in geography.get("regions", {}).values()),
    )
    points: list[tuple[int, int, int, str]] = []
    for kinds, province_key in ((("city",), "parent"), (("village", "town"), "province")):
        for table in tables:
            for entry in table:
                if entry["kind"] not in kinds or entry[province_key] is None:
                    continue
                points.append(
                    (
                        int(entry["state"]),
                        int(entry[province_key]),
                        int(entry["value"]),
                        str(entry["name"]),
                    )
                )
    return tuple(points)


def load_mon_settlement_points() -> tuple[tuple[int, int, int, str], ...]:
    return mon_settlement_points(load_mon_geography())


def state_province_lists(
    shells: dict[int, tuple[int, tuple[int, ...], str]],
    planned: dict[int, frozenset[int]],
) -> dict[int, tuple[int, ...]]:
    unknown = sorted(set(planned) - set(shells))
    if unknown:
        raise RuntimeError(f"MON plan names states outside the northern shells: {unknown}")
    owners = {
        province_id: state_id
        for state_id, (_parsed_id, provinces, _climate) in shells.items()
        for province_id in provinces
    }
    for state_id, provinces in planned.items():
        for province_id in sorted(provinces):
            if owners.get(province_id, state_id) != state_id:
                raise RuntimeError(
                    f"planned province {province_id} of state {state_id} is already in state {owners[province_id]}"
                )
    return {
        state_id: tuple(sorted(set(provinces) | planned.get(state_id, frozenset())))
        for state_id, (_parsed_id, provinces, _climate) in shells.items()
    }


def check_mon_settlements(
    state_provinces: dict[int, tuple[int, ...]],
    cities: dict[int, int],
    points: tuple[tuple[int, int, int, str], ...],
    scope: frozenset[int],
) -> None:
    """Every scope state needs one city; every victory point lies once in its own state."""
    if set(cities) != scope:
        raise RuntimeError(
            f"settlement table needs one city per state: missing={sorted(scope - set(cities))}, "
            f"unexpected={sorted(set(cities) - scope)}"
        )
    seen: set[int] = set()
    for state_id, province_id, _value, name in points:
        if state_id not in scope or province_id not in state_provinces[state_id]:
            raise RuntimeError(f"settlement {name}: province {province_id} is outside state {state_id}")
        if province_id in seen:
            raise RuntimeError(f"settlement {name}: province {province_id} already holds a victory point")
        seen.add(province_id)


def scope_victory_points(
    tag: str,
    country: dict[str, object],
    principal_provinces: dict[int, int],
    points: tuple[tuple[int, int, int, str], ...],
    scope: frozenset[int],
) -> dict[int, list[tuple[int, int, str]]]:
    """Return the victory points of a country's states.

    States in the geography scope take their settlement points, city first.
    Other states keep the manifest capital and secondary centres.
    """
    victory_points: dict[int, list[tuple[int, int, str]]] = {}
    for state_id, province_id, value, name in points:
        if state_id in country["states"]:
            victory_points.setdefault(state_id, []).append((province_id, value, name))
    if "capital_name" not in country:
        return victory_points
    capital = int(country["capital"])
    if capital in scope:
        city_name = victory_points[capital][0][2]
        if city_name != country["capital_name"]:
            raise RuntimeError(
                f"{tag}: capital {country['capital_name']} is named {city_name} in the geography table"
            )
    else:
        victory_points[capital] = [
            (principal_provinces[capital], 5, str(country["capital_name"]))
        ]
    for state_id, name, value in country.get("secondary_vps", ()):
        if int(state_id) not in scope:
            victory_points[int(state_id)] = [
                (principal_provinces[int(state_id)], int(value), str(name))
            ]
    return victory_points


def build_profiles() -> tuple[dict[int, dict[str, object]], dict[int, int]]:
    color_to_province, details = load_definition()
    areas = load_pixel_areas(color_to_province)
    positions = load_positions()
    shells = {
        state_id: parse_state(state_path(state_id)) for state_id in EXPECTED_STATES
    }
    geography = load_mon_geography()
    # The MON region and the TMR, VEL and DRV states; the inner-frontier
    # builder renders the other neighbour states from the same table.
    scope = geography_scope_states(geography) & EXPECTED_STATES
    planned = {
        state_id: provinces
        for state_id, provinces in mon_planned_provinces(geography, details).items()
        if state_id in scope
    }
    state_provinces = state_province_lists(shells, planned)
    mon_cities = {
        state_id: province_id
        for state_id, province_id in mon_city_parents(geography).items()
        if state_id in scope
    }
    mon_points = tuple(
        point for point in mon_settlement_points(geography) if point[0] in scope
    )
    check_mon_settlements(state_provinces, mon_cities, mon_points, scope)
    principal_provinces: dict[int, int] = {}
    state_pixels: dict[int, int] = {}
    for state_id, provinces in state_provinces.items():
        total_pixels = sum(areas[province_id] for province_id in provinces)
        state_pixels[state_id] = total_pixels
        if state_id in mon_cities:
            principal_provinces[state_id] = mon_cities[state_id]
            continue
        available = [
            province_id for province_id in provinces if province_id in positions
        ]
        if not available:
            principal_provinces[state_id] = min(provinces)
            continue
        center_x = sum(
            positions[province_id][0] * areas[province_id] for province_id in available
        ) / sum(areas[province_id] for province_id in available)
        center_y = sum(
            positions[province_id][1] * areas[province_id] for province_id in available
        ) / sum(areas[province_id] for province_id in available)
        principal_provinces[state_id] = min(
            available,
            key=lambda province_id: (
                (positions[province_id][0] - center_x) ** 2
                + (positions[province_id][1] - center_y) ** 2,
                -areas[province_id],
                province_id,
            ),
        )

    profiles: dict[int, dict[str, object]] = {}
    economies = {tag: country for tag, country in COUNTRIES.items() if tag not in MONTAR_SUCCESSORS}
    economies["Montar region"] = {**MONTAR_ECONOMY, "states": sorted(MONTAR_STATES)}
    for tag, country in economies.items():
        states = list(country["states"])
        if not states:
            continue
        capital = int(country["capital"])
        population_weights: dict[int, float] = {}
        for state_id in states:
            climate = shells[state_id][2]
            climate_factor = (
                0.42
                if climate == "right_polar"
                else 0.68 if "subarctic" in climate or "cold" in climate else 1.0
            )
            capital_factor = 2.2 if state_id == capital else 1.0
            population_weights[state_id] = (
                math.sqrt(state_pixels[state_id]) * climate_factor * capital_factor
            )
        populations = largest_remainder(int(country["population"]), population_weights)
        ranking = [capital] + sorted(
            (state_id for state_id in states if state_id != capital),
            key=lambda state_id: (-populations[state_id], state_id),
        )
        civilians = distribute_levels(
            int(country["civilian"]), ranking, 5 if tag == "Montar region" else 3
        )
        military = distribute_levels(
            int(country["military"]), ranking, 4 if tag == "Montar region" else 3
        )
        air_bases = distribute_levels(int(country["air_bases"]), ranking, 2)
        resources_by_state: dict[int, Counter[str]] = {
            state_id: Counter() for state_id in states
        }
        resource_ranking = sorted(
            states, key=lambda state_id: (-state_pixels[state_id], state_id)
        )
        for resource_index, (resource, total) in enumerate(
            country["resources"].items()
        ):
            deposits = min(len(resource_ranking), max(1, min(3, int(total) // 3)))
            targets = [
                resource_ranking[(resource_index + offset) % len(resource_ranking)]
                for offset in range(deposits)
            ]
            distributed = largest_remainder(
                int(total), {state_id: 1.0 for state_id in targets}
            )
            for state_id, amount in distributed.items():
                resources_by_state[state_id][resource] += amount

        victory_points = scope_victory_points(
            tag, country, principal_provinces, mon_points, scope
        )

        for state_id in states:
            population = populations[state_id]
            factory_total = civilians[state_id] + military[state_id]
            if factory_total > 4:
                category = "large_town"
            elif state_id == capital:
                category = "large_town" if population >= 750_000 else "town"
            elif population >= 700_000 or factory_total > 2:
                # Rural states have only two shared slots, even after population shifts.
                category = "town"
            else:
                category = "rural"
            infrastructure = min(
                5, int(country["infrastructure"]) + (1 if state_id == capital else 0)
            )
            profiles[state_id] = {
                "owner": STATE_OWNER[state_id],
                "population": population,
                "category": category,
                "infrastructure": infrastructure,
                "civilian": civilians[state_id],
                "military": military[state_id],
                "air_base": air_bases[state_id],
                "resources": dict(resources_by_state[state_id]),
                "victory_points": tuple(victory_points.get(state_id, ())),
                "local_supplies": round(
                    min(8.0, 0.75 + infrastructure * 0.55 + factory_total * 0.18), 1
                ),
                "climate": shells[state_id][2],
                "provinces": state_provinces[state_id],
            }
    for state_id, fixed in EXZ_FRINGE_STATE_PROFILES.items():
        profiles[state_id] = {
            "owner": "EXZ",
            **fixed,
            "victory_points": (),
            "climate": shells[state_id][2],
            "provinces": state_provinces[state_id],
        }
    return profiles, principal_provinces


def render_state(state_id: int, profile: dict[str, object]) -> str:
    history = [
        "\thistory = {",
        f"\t\towner = {profile['owner']}",
        f"\t\tadd_core_of = {profile['owner']}",
    ]
    if state_id in (426, 436, 454, 455):
        history.append("\t\tadd_core_of = ORV")
    for province_id, value, _name in profile["victory_points"]:
        history.append(f"\t\tvictory_points = {{ {province_id} {value} }}")
    history.extend(
        (
            "\t\tbuildings = {",
            f"\t\t\tinfrastructure = {profile['infrastructure']}",
        )
    )
    if profile["civilian"]:
        history.append(f"\t\t\tindustrial_complex = {profile['civilian']}")
    if profile["military"]:
        history.append(f"\t\t\tarms_factory = {profile['military']}")
    if profile["air_base"]:
        history.append(f"\t\t\tair_base = {profile['air_base']}")
    for province in ISLAND_SUPPLY_PORTS.get(state_id, ()):
        if province not in profile["provinces"]:
            raise ValueError(f"State {state_id}: port {province} is outside its territory")
        history.append(f"\t\t\t{province} = {{ naval_base = 1 }}")
    history.extend(("\t\t}", "\t}"))

    resources: list[str] = []
    if profile["resources"]:
        resources.append("\tresources = {")
        for resource, amount in sorted(profile["resources"].items()):
            resources.append(f"\t\t{resource} = {amount}")
        resources.append("\t}")

    lines = [
        OUTER_MARKER,
        POPULATION_MARKER,
        f"# adiscord_climate_region = {profile['climate']}",
        "state = {",
        f"\tid = {state_id}",
        f'\tname = "STATE_{state_id}"',
        f"\tmanpower = {profile['population']}",
        f"\tstate_category = {profile['category']}",
        *history,
        "\tprovinces = {",
        format_provinces(profile["provinces"]),
        "\t}",
        *resources,
        "\tbuildings_max_level_factor = 1.000",
        f"\tlocal_supplies = {profile['local_supplies']:.1f}",
        "}",
        "",
    ]
    return "\n".join(lines)


def regiment_block(unit_type: str, count: int) -> list[str]:
    return [
        f"\t\t{unit_type} = {{ x = {index % 3} y = {index // 3} }}"
        for index in range(count)
    ]


def render_oob(
    tag: str, country: dict[str, object], principal_provinces: dict[int, int]
) -> str:
    states = [int(country["capital"])] + [
        int(state_id)
        for state_id in country["states"]
        if state_id != country["capital"]
    ]
    divisions = int(country["divisions"])
    unit_type = str(country["unit_type"])
    if tag in MONTAR_SUCCESSORS:
        line_divisions = int(country["line_divisions"])
        lines = [
            "division_template = {",
            f'\tname = "{IMPERIAL_LINE_TEMPLATE}"',
            "\ttemplate_counter = 3",
            "\tregiments = {",
            *regiment_block("infantry", 6),
            "\t\tADISCORD_line_artillery = { x = 2 y = 2 }",
            "\t}",
            "}",
            "division_template = {",
            f'\tname = "{IMPERIAL_FRONTIER_TEMPLATE}"',
            "\ttemplate_counter = 3",
            "\tregiments = {",
            *regiment_block("infantry", 4),
            "\t}",
            "}",
            "units = {",
        ]
        for index in range(divisions):
            template = (
                IMPERIAL_LINE_TEMPLATE if index < line_divisions else IMPERIAL_FRONTIER_TEMPLATE
            )
            lines.append(
                f'\tdivision = {{ division_name = {{ is_name_ordered = yes name_order = {index+1} }} '
                f'location = {principal_provinces[states[index % len(states)]]} division_template = "{template}" '
                f"start_experience_factor = {0.30 if index < line_divisions else 0.20:.2f} start_equipment_factor = 1.00 }}"
            )
        lines.extend(("}", ""))
        return "\n".join(lines)

    template = (
        NORTHERN_LINE_TEMPLATE if unit_type == "infantry" else NORTHERN_MILITIA_TEMPLATE
    )
    regiment_count = 4 if unit_type == "infantry" else 3
    lines = [
        "division_template = {",
        f'\tname = "{template}"',
        f"\ttemplate_counter = {3 if unit_type == 'infantry' else 7}",
        "\tregiments = {",
        *regiment_block(unit_type, regiment_count),
        "\t}",
        "}",
        "units = {",
    ]
    for index in range(divisions):
        lines.append(
            f'\tdivision = {{ division_name = {{ is_name_ordered = yes name_order = {index+1} }} '
            f'location = {principal_provinces[states[index % len(states)]]} division_template = "{template}" '
            f"start_experience_factor = 0.15 start_equipment_factor = 0.72 }}"
        )
    lines.extend(("}", ""))
    return "\n".join(lines)


def update_oobs(principal_provinces: dict[int, int], *, apply: bool) -> list[str]:
    # Orval can be released in state 455 but owns no partition at game start.
    armies = {
        **COUNTRIES,
        "ORV": {"capital": 455, "states": (455,), "divisions": 1, "unit_type": "infantry"},
    }
    changed = []
    for tag, country in armies.items():
        path = UNIT_DIR / f"{tag}.txt"
        output = render_oob(tag, country, principal_provinces)
        if not path.exists() or path.read_text(encoding="utf-8") != output:
            changed.append(tag)
            if apply:
                path.write_text(output, encoding="utf-8", newline="\n")
    return changed


