#!/usr/bin/env python3
"""Split the old catch-all state 23 into coarse, climate-coherent state shells.

The detailed northern/right and provisional left-continent shells are handled
by ``build_adiscord_outer_states.py``.  This pass only handles what remains in
state 23. The country and western manifests preserve the surveyed shells,
including their IDs, province membership, names and climates. Western states
take their final geometry and names from the authored western partition.

State 23 is retained as one real connected shell; the other shells use IDs
551 and above.  Re-running the tool folds its own marked files back into the
source pool before rebuilding them.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from tools.builders.build_adiscord_map_buildings import synchronize_buildings
from tools.builders.build_adiscord_new_states import (
    raised_island_provinces,
    with_raised_island_provinces,
)
from tools.builders.build_adiscord_outer_states import (
    ProvinceData,
    build_province_data,
    cluster_statistics,
    format_provinces,
    parse_state,
    render_western_id,
    western_source,
)
from tools.builders.build_adiscord_strategic_regions import (
    load_province_definitions,
)
from tools.lib.paths import repository_root
from tools.lib.localisation import replace_generated_localisation_block
from tools.lib.adiscord_remainder_countries import (
    COUNTRIES,
    SOURCE as REMAINDER_SOURCE,
    RAISED_ISLAND_PROVINCES,
    synchronize,
)


ROOT = repository_root()
STATE_DIR = ROOT / "history" / "states"
LOCALISATION = ROOT / "localisation" / "russian" / "state_names_l_russian.yml"
BASE_STATE_LOCALISATION = (
    ROOT / "localisation" / "russian" / "state_names_l_russian.yml"
)
GENERATED_MARKER = "# Generated by tools/build_adiscord_remainder_states.py"
CLIMATE_MARKER = "# adiscord_climate_region = "
STRATEGIC_NAME_MARKER = "# adiscord_strategic_name = "
FIRST_NEW_STATE_ID = 551
# The archipelago table adds raised islets after the surveyed state partition.
EXPECTED_PROVINCE_COUNT = 1004

LATITUDE_EDGES = (350.0, 650.0, 1050.0, 1450.0, 1750.0)


@dataclass
class PlannedState:
    state_id: int
    provinces: set[int]
    climate_region: str
    name: str
    strategic_name: str


def state_23_path() -> Path:
    matches = sorted(STATE_DIR.glob("23-*.txt"))
    if len(matches) != 1:
        raise RuntimeError(f"state 23: expected one file, found {len(matches)}")
    return matches[0]


def without_raised_islands(state_id: int, provinces: set[int]) -> set[int]:
    """Return the surveyed provinces after checking the state's raised islets."""
    raised = provinces & RAISED_ISLAND_PROVINCES
    expected = raised_island_provinces(state_id)
    if raised != expected:
        raise RuntimeError(
            f"state {state_id}: raised island provinces {sorted(raised)} differ "
            f"from the archipelago table {sorted(expected)}"
        )
    return provinces - raised


def load_source_pool() -> tuple[set[int], str, list[Path]]:
    base_path = state_23_path()
    _state_id, base_provinces, base_source = parse_state(base_path)
    pool = without_raised_islands(23, set(base_provinces))
    generated_paths: list[Path] = []
    for path in sorted(STATE_DIR.glob("*.txt")):
        if path == base_path:
            continue
        source = path.read_text(encoding="utf-8-sig", errors="strict")
        if not source.startswith(GENERATED_MARKER):
            continue
        state_id, provinces, _source = parse_state(path)
        provinces = without_raised_islands(state_id, provinces)
        # The western manifest keeps separate surveyed and final island groups.
        if str(state_id) in western_source().get("source_partitions", {}):
            provinces = set(western_source()["source_partitions"][str(state_id)]["provinces"])
        if state_id < FIRST_NEW_STATE_ID:
            raise RuntimeError(
                f"{path.name}: remainder marker on reserved state id {state_id}"
            )
        overlap = pool & provinces
        if overlap:
            raise RuntimeError(
                f"remainder states overlap at provinces {sorted(overlap)[:20]}"
            )
        pool.update(provinces)
        generated_paths.append(path)
    if len(pool) != EXPECTED_PROVINCE_COUNT:
        raise RuntimeError(
            f"remainder source pool changed: expected {EXPECTED_PROVINCE_COUNT} provinces, found {len(pool)}"
        )
    return pool, base_source, generated_paths


def band_for_y(y: float) -> int:
    return next(
        (index for index, edge in enumerate(LATITUDE_EDGES) if y < edge),
        len(LATITUDE_EDGES),
    )


def plan_states() -> list[PlannedState]:
    # Western islands retain their surveyed IDs even when later coastal work
    # splits a source province group into disconnected islands.
    shells = json.loads(REMAINDER_SOURCE.read_text(encoding="utf-8"))["state_shells"]
    for state_id, row in western_source()["source_partitions"].items():
        if int(state_id) >= FIRST_NEW_STATE_ID:
            if state_id in shells:
                raise ValueError(f"state {state_id}: duplicate remainder shell")
            shells[state_id] = row
    return [
        PlannedState(
            int(state_id), set(row["provinces"]), row["climate"],
            row["strategic_name"], row["strategic_name"],
        )
        for state_id, row in sorted(shells.items(), key=lambda item: int(item[0]))
    ]


def render_state(state: PlannedState, data: dict[int, ProvinceData]) -> str:
    if str(state.state_id) in western_source()["states"]:
        return render_western_id(state.state_id)
    stats = cluster_statistics(state.provinces, data)
    band = band_for_y(float(stats["y"]))
    category = (
        "wasteland" if band == 0 or float(stats["highland_share"]) >= 0.70 else "rural"
    )
    rendered = (
        f"{GENERATED_MARKER}\n"
        f"{CLIMATE_MARKER}{state.climate_region}\n"
        f"{STRATEGIC_NAME_MARKER}{state.strategic_name}\n"
        "state = {\n"
        f"\tid = {state.state_id}\n"
        f'\tname = "STATE_{state.state_id}"\n'
        "\tmanpower = 1\n"
        f"\tstate_category = {category}\n"
        "\tprovinces = {\n"
        f"{format_provinces(state.provinces)}\n"
        "\t}\n"
        "\tbuildings_max_level_factor = 1.000\n"
        "\tlocal_supplies = 0.0\n"
        "}\n"
    )
    return with_raised_island_provinces(rendered, state.state_id)


def update_state_23_localisation(name: str) -> None:
    source = BASE_STATE_LOCALISATION.read_text(encoding="utf-8-sig", errors="strict")
    updated, count = re.subn(
        r'(?m)^(\s*STATE_23\s*:\s*)"[^"]*"',
        lambda match: f'{match.group(1)}"{name}"',
        source,
    )
    if count != 1:
        raise RuntimeError(f"STATE_23 localisation: expected one row, found {count}")
    BASE_STATE_LOCALISATION.write_text(
        "\ufeff" + updated, encoding="utf-8", newline="\n"
    )


def validate_plan(planned: list[PlannedState], pool: set[int]) -> None:
    assigned: set[int] = set()
    for state in planned:
        overlap = assigned & state.provinces
        if overlap:
            raise RuntimeError(
                f"planned remainder states overlap at {sorted(overlap)[:20]}"
            )
        assigned.update(state.provinces)
    if assigned != pool:
        raise RuntimeError(
            f"planned remainder coverage mismatch: missing {len(pool-assigned)}, unexpected {len(assigned-pool)}"
        )
    expected_ids = {
        23,
        *range(FIRST_NEW_STATE_ID, FIRST_NEW_STATE_ID + len(planned) - 1),
    }
    actual_ids = {state.state_id for state in planned}
    if actual_ids != expected_ids:
        raise RuntimeError(
            f"planned remainder IDs differ: expected {sorted(expected_ids)}, found {sorted(actual_ids)}"
        )
    names = Counter(state.name for state in planned)
    duplicates = sorted(name for name, count in names.items() if count > 1)
    if duplicates:
        raise RuntimeError(f"duplicate remainder names: {duplicates}")
    technical = [
        state.name for state in planned if re.search(r"\s[IVXLCDM]+$", state.name)
    ]
    if technical:
        raise RuntimeError(f"technical numeral names remain: {technical}")


def apply_plan(
    planned: list[PlannedState],
    data: dict[int, ProvinceData],
    generated_paths: list[Path],
) -> None:
    for path in generated_paths:
        path.unlink()
    for state in planned:
        path = (
            state_23_path()
            if state.state_id == 23
            else STATE_DIR / f"{state.state_id}-outer-remainder.txt"
        )
        path.write_text(render_state(state, data), encoding="utf-8", newline="\n")

    generated = [state for state in planned if state.state_id != 23]
    replace_generated_localisation_block(
        LOCALISATION,
        "tools.builders.build_adiscord_remainder_states",
        {
            f"STATE_{state.state_id}": western_source()["states"].get(str(state.state_id), {}).get("name", state.name)
            for state in generated
        },
    )
    state_23 = next(state for state in planned if state.state_id == 23)
    update_state_23_localisation(state_23.name)
    print(
        f"Applied {len(planned)} connected remainder shells: state 23 plus "
        f"{len(generated)} states {FIRST_NEW_STATE_ID}-{generated[-1].state_id}."
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument(
        "--check",
        action="store_true",
        help="validate current generated outputs (default)",
    )
    actions.add_argument(
        "--apply",
        action="store_true",
        help="write generated state files and localisation",
    )
    parser.add_argument(
        "--countries-only",
        action="store_true",
        help="check or populate political history without rebuilding geography",
    )
    parser.add_argument(
        "--english-localisation",
        action="store_true",
        help="check or apply only reviewed English names",
    )
    parser.add_argument(
        "--flags-only",
        nargs="+",
        choices=tuple(COUNTRIES),
        metavar="TAG",
        help="check or apply only the named countries' flag textures",
    )
    args = parser.parse_args()
    if args.flags_only:
        if args.countries_only or args.english_localisation:
            parser.error("--flags-only cannot be combined with other scoped actions")
        changed = synchronize(apply=args.apply, flags_only=tuple(args.flags_only))
        for path in changed:
            print(("Updated: " if args.apply else "Drift: ") + path)
        if not changed:
            print("Selected remainder-country flags are current.")
        return int(bool(changed) and not args.apply)
    if args.countries_only:
        changed = synchronize(apply=args.apply)
        print(f"Remainder-country outputs {'updated' if args.apply else 'different'}: {len(changed)}")
        for path in changed:
            print(path)
        return int(bool(changed) and not args.apply)
    if args.english_localisation:
        from tools.lib.localisation import sync_builder_english_localisation

        return sync_builder_english_localisation(
            ROOT, "tools.builders.build_adiscord_remainder_states", apply=args.apply
        )

    if not args.apply:
        from tools.validators.validate_adiscord_remainder_states import (
            main as validate_main,
        )

        return validate_main()

    pool, _base_source, generated_paths = load_source_pool()
    province_types, color_to_province = load_province_definitions()
    data = build_province_data(province_types, color_to_province)
    if not pool <= set(data):
        raise RuntimeError(
            f"remainder pool contains non-land provinces {sorted(pool-set(data))[:20]}"
        )
    planned = plan_states()
    validate_plan(planned, pool)
    climate_counts = Counter(state.climate_region for state in planned)
    print(
        f"Planned {len(planned)} connected climate shells from {len(pool)} provinces."
    )
    print(f"Climate groups: {dict(sorted(climate_counts.items()))}")
    apply_plan(planned, data, generated_paths)
    changed = synchronize(apply=True)
    print(f"Synchronized {len(changed)} remainder-country outputs.")
    mismatches = synchronize_buildings(ROOT, apply=True)
    print(f"Synchronized {len(mismatches)} map-building state assignments.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
