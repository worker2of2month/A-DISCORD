def managed_localisation(path, content):
    source = (ROOT / path).read_bytes()
    newline = b"\r\n" if b"\r\n" in source else b"\n"
    replacement = BEGIN.encode() + newline + content.replace("\n", newline.decode()).encode("utf-8") + END.encode() + newline
    if BEGIN.encode() in source:
        pattern = rb"(?m)^" + BEGIN.encode() + rb"\r?\n.*?^" + END.encode() + rb"\r?\n"
        updated, count = re.subn(pattern, lambda _: replacement, source, flags=re.S)
        if count != 1:
            raise ValueError(f"Ambiguous generated section: {path}")
        return updated
    return source + newline + replacement


def build_outputs():
    images, geometry = render_images()
    outputs = {}
    for filename, image in images.items():
        stream = io.BytesIO()
        image.save(stream, format="PNG", optimize=True)
        outputs[OUT / filename] = stream.getvalue()
    for path, content in ((GUI, gui(geometry)), (GFX, gfx(images)), (SGUI, scripted_gui(geometry))):
        outputs[path] = content.encode("utf-8")
    for language in ("russian", "english"):
        path = Path(f"localisation/{language}/ADISCORD_south_final_war_l_{language}.yml")
        outputs[path] = managed_localisation(path, localisation(geometry, language))
    return outputs, geometry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    outputs, geometry = build_outputs()
    changed = [path for path, value in outputs.items() if not (ROOT / path).exists() or (ROOT / path).read_bytes() != value]
    if args.apply:
        for path in changed:
            (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / path).write_bytes(outputs[path])
    print(f"South map: {len(geometry['states'])} states, {len(outputs)} outputs, {len(changed)} {'written' if args.apply else 'differences'}")
    return int(bool(changed) and not args.apply)


if __name__ == "__main__":
    raise SystemExit(main())
