"""Build the southern influence map from state history and province geometry.

Owns the map textures, GUI bindings and marked localisation sections.
The map reads campaign state without storing a second political ledger.
"""

from __future__ import annotations

import argparse
import csv
import io
import re
from pathlib import Path

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
OUT = Path("gfx/interface/south_influence")
GUI = Path("interface/ADISCORD_south_final_war.gui")
GFX = Path("interface/ADISCORD_south_final_war.gfx")
SGUI = Path("common/scripted_guis/ADISCORD_south_final_war_scripted_gui.txt")
WIDTH, HEIGHT = 436, 300
COUNTRIES = ("SHL", "NAM", "EFL", "AZH", "WEF", "KDR", "RHM", "SDR", "KYZ", "MZR", "GLP")
# Layer order keeps the leader shades above the light alliance fills.
PALETTE = ((104, 113, 114), (231, 174, 105), (119, 185, 220), (158, 82, 34), (38, 83, 133))
LAYERS = ("neutral", "shl", "north", "shl_leader", "north_leader", "occupied")
BEGIN = "# BEGIN GENERATED SOUTH INFLUENCE MAP"
END = "# END GENERATED SOUTH INFLUENCE MAP"
HEADER = "# Generated by tools/builders/build_adiscord_south_influence_map.py.\n"


def geography():
    colors = {}
    land = []
    with (ROOT / "map/definition.csv").open(encoding="utf-8-sig") as source:
        for row in csv.reader(source, delimiter=";"):
            if len(row) > 4 and row[0].isdigit():
                color = int(row[1]) * 65536 + int(row[2]) * 256 + int(row[3])
                colors[int(row[0])] = color
                if row[4] == "land":
                    land.append(color)
    states = {}
    for path in sorted((ROOT / "history/states").glob("*.txt")):
        source = re.sub(r"#.*", "", path.read_text(encoding="utf-8-sig"))
        owner = re.search(r"\bowner\s*=\s*(\w+)", source)
        if owner is None or owner[1] not in COUNTRIES:
            continue
        state = int(re.search(r"\bid\s*=\s*(\d+)", source)[1])
        provinces = re.search(r"\bprovinces\s*=\s*\{([^}]+)\}", source)[1]
        states[state] = {"owner": owner[1], "colors": [colors[int(p)] for p in re.findall(r"\d+", provinces)]}
    with Image.open(ROOT / "map/provinces.bmp") as image:
        rgb = np.asarray(image.convert("RGB"), dtype=np.uint32)
    packed = rgb[:, :, 0] * 65536 + rgb[:, :, 1] * 256 + rgb[:, :, 2]
    selected = np.isin(packed, [c for info in states.values() for c in info["colors"]])
    yy, xx = np.nonzero(selected)
    box = (max(0, int(xx.min()) - 22), max(0, int(yy.min()) - 22),
           min(packed.shape[1], int(xx.max()) + 23), min(packed.shape[0], int(yy.max()) + 23))
    # Expand the geographic viewport instead of stretching the coastline.
    scale = max((box[2] - box[0]) / WIDTH, (box[3] - box[1]) / HEIGHT)
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    box = (round(cx - WIDTH * scale / 2), round(cy - HEIGHT * scale / 2),
           round(cx + WIDTH * scale / 2), round(cy + HEIGHT * scale / 2))
    if box[0] < 0 or box[1] < 0 or box[2] > packed.shape[1] or box[3] > packed.shape[0]:
        raise ValueError("Southern viewport exceeds native map bounds")
    crop = packed[box[1]:box[3], box[0]:box[2]]

    def project(selection):
        return Image.fromarray(selection.astype(np.uint8) * 255).resize((WIDTH, HEIGHT), Image.Resampling.NEAREST)

    visible = {}
    for state, info in sorted(states.items()):
        mask = project(np.isin(crop, info["colors"]))
        bounds = mask.getbbox()
        if bounds:
            visible[state] = {"owner": info["owner"], "mask": mask, "box": bounds}
    return {"states": visible, "land": project(np.isin(crop, land)), "source_box": box}


def state_strip(mask, origin):
    width, height = mask.size
    strip = Image.new("RGBA", (width * len(LAYERS), height))
    rim = ImageChops.subtract(mask, mask.filter(ImageFilter.MinFilter(3)))
    for index, color in enumerate(PALETTE):
        frame = Image.new("RGBA", mask.size, (*color, 255))
        frame.paste(tuple(max(0, channel - 27) for channel in color), (0, 0, width, height), rim)
        frame.putalpha(mask)
        strip.paste(frame, (width * index, 0))
    yy, xx = np.indices((height, width))
    hatch = ((xx + origin[0] + yy + origin[1]) % 7 < 2).astype(np.uint8) * 145
    occupied = Image.new("RGBA", mask.size, (234, 220, 182, 255))
    occupied.putalpha(ImageChops.multiply(mask, Image.fromarray(hatch)))
    strip.paste(occupied, (width * len(PALETTE), 0))
    return strip


def render_images():
    geometry = geography()
    background = Image.new("RGBA", (WIDTH, HEIGHT), (18, 32, 41, 255))
    background.paste((45, 53, 52, 255), (0, 0, WIDTH, HEIGHT), geometry["land"])
    draw = ImageDraw.Draw(background)
    for x in range(16, WIDTH, 32):
        draw.line((x, 0, x, HEIGHT), fill=(49, 63, 66, 255))
    for y in range(12, HEIGHT, 32):
        draw.line((0, y, WIDTH, y), fill=(49, 63, 66, 255))
    draw.rectangle((0, 0, WIDTH - 1, HEIGHT - 1), outline=(108, 107, 87))
    draw.line((WIDTH - 22, 14, WIDTH - 22, 42), fill=(210, 198, 163), width=1)
    draw.polygon(((WIDTH - 22, 12), (WIDTH - 26, 22), (WIDTH - 18, 22)), fill=(210, 198, 163))
    images = {"background.png": background}
    for state, info in geometry["states"].items():
        images[f"state_{state}.png"] = state_strip(info["mask"].crop(info["box"]), info["box"][:2])
    for tag in COUNTRIES:
        with Image.open(ROOT / f"gfx/flags/medium/{tag}.tga") as image:
            images[f"flag_{tag}.png"] = image.convert("RGBA").resize((30, 19), Image.Resampling.LANCZOS)
    return images, geometry


def icon(name, sprite, x, y, frame=1, tooltip=None, passive=False):
    lines = ["\t\ticonType = {", f'\t\t\tname = "{name}"',
             f"\t\t\tposition = {{ x = {x} y = {y} }}", f'\t\t\tquadTextureSprite = "{sprite}"',
             f"\t\t\tframe = {frame}"]
    if tooltip:
        lines.append(f'\t\t\tpdx_tooltip = "{tooltip}"')
    if passive:
        lines.append("\t\t\talwaystransparent = yes")
    return "\n".join([*lines, "\t\t}"])


def textbox(name, key, x, y, width, height, tooltip=None):
    lines = ["\t\tinstantTextBoxType = {", f'\t\t\tname = "{name}"',
             f"\t\t\tposition = {{ x = {x} y = {y} }}", f'\t\t\ttext = "{key}"',
             '\t\t\tfont = "hoi_16mbs"', f"\t\t\tmaxWidth = {width}", f"\t\t\tmaxHeight = {height}",
             '\t\t\tfixedsize = yes']
    if tooltip:
        lines.append(f'\t\t\tpdx_tooltip = "{tooltip}"')
    else:
        lines.append('\t\t\talwaystransparent = yes')
    return "\n".join([*lines, '\t\t}'])


def gui(geometry):
    parts = [HEADER + 'guiTypes = {\n\tcontainerWindowType = {\n\t\tname = "ADISCORD_south_map_window"\n'
             '\t\tposition = { x = 0 y = 0 }\n\t\tsize = { width = 460 height = 474 }',
             textbox("ADISCORD_south_map_heading", "ADISCORD_south_map_heading", 12, 4, 436, 22, "ADISCORD_south_map_rules_tt"),
             icon("ADISCORD_south_map_background", "GFX_ADISCORD_south_map_background", 12, 30, passive=True)]
    for state, info in geometry["states"].items():
        name = f"ADISCORD_south_map_state_{state}"
        x, y = info["box"][:2]
        for frame, suffix in enumerate(LAYERS, 1):
            parts.append(icon(name + "_" + suffix, "GFX_" + name, 12 + x, 30 + y, frame, name + "_tt"))
    for index, tag in enumerate(COUNTRIES):
        parts.append(icon(f"ADISCORD_south_map_flag_{tag}", f"GFX_ADISCORD_south_map_flag_{tag}",
                          15 + index * 39, 341, tooltip=f"ADISCORD_south_map_{tag}_tt"))
    parts.extend([
        textbox("ADISCORD_south_map_legend", "ADISCORD_south_map_legend", 12, 370, 436, 54, "ADISCORD_south_map_rules_tt"),
        textbox("ADISCORD_south_map_readiness", "ADISCORD_south_map_readiness", 12, 432, 436, 34, "ADISCORD_south_map_status_tt"),
        '\t}\n}\n',
    ])
    return "\n\n".join(parts)


def gfx(images):
    parts = [HEADER + "spriteTypes = {"]
    for filename in images:
        name = Path(filename).stem
        frames = len(LAYERS) if name.startswith("state_") else 1
        parts.append("\n".join(['\tspriteType = {', f'\t\tname = "GFX_ADISCORD_south_map_{name}"',
                                f'\t\ttexturefile = "{(OUT / filename).as_posix()}"',
                                f'\t\tnoOfFrames = {frames}', '\t\ttransparencecheck = yes', '\t}']))
    return "\n\n".join([*parts, "}\n"])


def scripted_gui(geometry):
    lines = [HEADER + 'scripted_gui = {\n\tADISCORD_south_map_panel = {',
             '\t\tcontext_type = decision_category', '\t\twindow_name = "ADISCORD_south_map_window"',
             '\t\tvisible = { always = yes }', '\t\tai_enabled = { always = no }',
             '\t\t# Ownership and control have no shared dirty variable; refresh only while this category is drawn.',
             '\t\ttriggers = {']
    for state in geometry["states"]:
        name = f"ADISCORD_south_map_state_{state}"
        for side in LAYERS[1:]:
            lines.extend([f'\t\t\t{name}_{side}_visible = {{',
                          f'\t\t\t\t{state} = {{ ADISCORD_south_map_state_{side} = yes }}', '\t\t\t}'])
    lines.extend(['\t\t}', '\t}', '}', ''])
    return "\n".join(lines)


