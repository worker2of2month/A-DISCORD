ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.assets.source.build_shl_palace import dds_bytes, load_exporter

DIRECTORY = Path("gfx/models/buildings/ADISCORD_map_facilities")
REPORT = Path("docs/development/model-verification/map_facility_models.json")
SOURCE = Path("tools/assets/source/buildings")
SCENES = {
    "bunker": SOURCE / "bunkers/bunker_prototype.blend",
    "bunker_destroyed": SOURCE / "bunkers/bunker_destroyed_prototype.blend",
    "air_base": SOURCE / "airfield/airfield_prototype.blend",
    "air_base_destroyed": SOURCE / "airfield/airfield_damaged_prototype.blend",
    "dockyard": SOURCE / "dockyard/dockyard_prototype.blend",
    "dockyard_destroyed": SOURCE / "dockyard/dockyard_damaged_prototype.blend",
    "naval_base": SOURCE / "port/port_prototype.blend",
    "naval_base_destroyed": SOURCE / "port/port_damaged_prototype.blend",
}
INPUTS = [Path(__file__).relative_to(ROOT), Path("tools/assets/source/build_shl_palace.py"), *SCENES.values()]
GFX = Path("gfx/entities/mapitems_custom.gfx")
ENTITIES = Path("gfx/entities/zz_ADISCORD_building_entities.asset")
MARKER = "ADISCORD map facility models"
SIZE = 1024
CHANNELS = ("diffuse", "normal", "specular")
PORT_SCALE = .405
# Authoring coordinates before the uniform map transform.
DAMAGE = {
    "bunker": [],
    "bunker_destroyed": [(-.5, -1.7, .6), (.45, -2.7, .40)],
    "air_base": [(-3.2, 3.4, 1.5), (.4, 3.4, 1.5), (4.2, 2.85, 1.95)],
    "air_base_destroyed": [(-3.2, 3.35, .5), (-3.0, 2.4, .4), (-3.4, 3.9, .6)],
    "dockyard": [(-2.6, 2.9, 1.85), (1.3, -.3, 1.1)],
    "dockyard_destroyed": [(-2.6, 2.9, .6), (2.3, -.65, .85)],
    "naval_base": [(-2.45, -4.72, 2.04), (-3.07, 2.08, 1.98), (1.63, 2.93, 1.60)],
    "naval_base_destroyed": [(-1.25, -4.82, .63), (-3.07, 2.08, .74), (1.63, 2.93, 1.60)],
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def name(kind):
    return "ADISCORD_map_" + kind


def files(kind):
    prefix = name(kind)
    return [prefix + ".mesh", *(f"{prefix}_{channel}.dds" for channel in CHANNELS)]


def map_point(kind, point):
    x, y, z = point
    if kind.startswith("naval_base"):
        # Both quays project along native -Z. Match the original outer pier
        # at Z = -3.13 relative to the shared coastal spawn point.
        return (PORT_SCALE * x, PORT_SCALE * y - .85, PORT_SCALE * z)
    if kind.startswith("dockyard"):
        # +X in the study faces the sea. The vanilla quay faces native -Z.
        return (.293 * (y - .5), -.293 * x - .904, .293 * z)
    if kind.startswith("air_base"):
        return (.351 * x + .43, .351 * y - .09, .351 * z)
    return (.325 * (x - .65) + .26, .325 * y - .06, .325 * z)


def entity(kind):
    lines = ["entity = {", f'\tname = "building_{kind}"', "\tversion = 1",
             f'\tpdxmesh = "{name(kind)}_mesh"']
    for i, point in enumerate(DAMAGE[kind], 1):
        x, y, z = map_point(kind, point)
        lines.extend(["\tlocator = {", f'\t\tname = "damage_{i}"',
                      f"\t\tposition = {{ {x:.6f} {z:.6f} {y:.6f} }}", "\t}"])
    lines.append('\tdefault_state = "idle"')
    destroyed = kind.endswith("_destroyed")
    states = ["idle"] if destroyed or kind == "bunker" else ["idle", "damaged"]
    for state in states:
        lines.extend(["\tstate = {", f'\t\tname = "{state}"'])
        if destroyed or state == "damaged":
            effects = [(i, "building_damaged_particle", .1) for i in range(1, len(DAMAGE[kind]) + 1)]
            if kind == "bunker_destroyed":
                effects.append((1, "bunker_smoke_effect", 0))
            for i, particle, time in effects:
                lines.extend(["\t\tevent = {", f"\t\t\ttime = {time}", f'\t\t\tnode = "damage_{i}"',
                              f'\t\t\tparticle = "{particle}"', "\t\t}"])
        lines.append("\t}")
    return "\n".join(lines + ["}"])


def sections():
    definitions = ['\tpdxmesh = {\n' + f'\t\tname = "{name(k)}_mesh"\n'
                   + f'\t\tfile = "{DIRECTORY.as_posix()}/{name(k)}.mesh"\n\t\tscale = 1\n\t}}'
                   for k in SCENES]
    return {GFX: "objectTypes = {\n" + "\n\n".join(definitions) + "\n}",
            ENTITIES: "\n\n".join(entity(k) for k in SCENES)}


def registry_bytes(path, body):
    old = (ROOT / path).read_bytes()
    begin, end = ("# BEGIN " + MARKER).encode(), ("# END " + MARKER).encode()
    newline = b"\r\n" if b"\r\n" in old else b"\n"
    section = newline.join([begin, b"# Generated by tools/builders/build_adiscord_map_facility_models.py",
                            body.encode().replace(b"\n", newline), end, b""])
    if old.count(begin) != old.count(end) or old.count(begin) > 1:
        raise ValueError(f"Ambiguous ownership markers in {path}")
    if begin not in old:
        if b"ADISCORD_map_bunker_mesh" in old:
            raise ValueError(f"Unmarked model definition in {path}")
        return old.rstrip(b"\r\n") + newline * 2 + section
    first = old.index(begin)
    last = old.index(end, first) + len(end)
    return old[:first] + section.rstrip(b"\r\n") + old[last:]


def input_hashes():
    return {path.as_posix(): digest(ROOT / path) for path in INPUTS}


def stale():
    result = [str(p) for p, block in sections().items() if (ROOT / p).read_bytes() != registry_bytes(p, block)]
    report = json.loads((ROOT / REPORT).read_text()) if (ROOT / REPORT).exists() else {}
    if report.get("inputs") != input_hashes() or not report.get("native_reimport"):
        result.append(str(REPORT))
    for kind in SCENES:
        for filename in files(kind):
            path = ROOT / DIRECTORY / filename
            if not path.is_file() or digest(path) != report.get("files", {}).get(filename):
                result.append(str(DIRECTORY / filename))
    return result


def assemble(kind):
    import bpy

    bpy.ops.wm.open_mainfile(filepath=str(ROOT / SCENES[kind]))
    objects = list(bpy.context.scene.objects)
    vertices, faces, normals, materials, indices = [], [], [], [], []
    for obj in objects:
        if obj.type != "MESH" or obj.name.startswith("REVIEW"):
            continue
        matrix = obj.matrix_world
        normal_matrix = matrix.to_3x3().inverted().transposed()
        data = obj.data
        data.calc_loop_triangles()
        offset = len(vertices)
        vertices.extend(matrix @ v.co for v in data.vertices)
        for tri in data.loop_triangles:
            faces.append(tuple(offset + i for i in tri.vertices))
            normals.extend((normal_matrix @ data.corner_normals[i].vector).normalized() for i in tri.loops)
            mat = obj.material_slots[tri.material_index].material
            if mat not in materials:
                materials.append(mat)
            indices.append(materials.index(mat))
    for obj in objects:
        bpy.data.objects.remove(obj, do_unlink=True)
    data = bpy.data.meshes.new(name(kind))
    data.from_pydata(vertices, [], faces)
    data.update()
    data.normals_split_custom_set(normals)
    for mat in materials:
        data.materials.append(mat)
    data.polygons.foreach_set("material_index", indices)
    obj = bpy.data.objects.new(name(kind), data)
    bpy.context.collection.objects.link(obj)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.uv.smart_project(island_margin=.003, scale_to_bounds=True)
    bpy.ops.object.mode_set(mode="OBJECT")
    return obj


def bake(obj, kind, stage):
    import bpy

    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.samples = 1
    scene.render.bake.margin = 5
    scene.render.bake.margin_type = "EXTEND"
    scene.render.bake.use_pass_direct = False
    scene.render.bake.use_pass_indirect = False
    for channel, mode in (("diffuse", "DIFFUSE"), ("normal", "NORMAL"), ("roughness", "ROUGHNESS")):
        image = bpy.data.images.new(channel, width=SIZE, height=SIZE, alpha=False, is_data=channel != "diffuse")
        for material in obj.data.materials:
            nodes = material.node_tree.nodes
            target = nodes.new("ShaderNodeTexImage")
            target.image = image
            nodes.active = target
        bpy.ops.object.bake(type=mode, uv_layer=obj.data.uv_layers.active.name)
        image.filepath_raw = str(stage / f"{name(kind)}_{channel}.png")
        image.file_format = "PNG"
        image.save()
        for material in obj.data.materials:
            nodes = material.node_tree.nodes
            nodes.remove(nodes.active)


def write_meshes(stage):
    import bpy
    from mathutils import Matrix, Vector

    pdx = load_exporter()
    from io_pdx_mesh import pdx_data
    manifest = {}
    for kind in SCENES:
        obj = assemble(kind)
        bake(obj, kind, stage)
        # Uniform scale and rotation preserve the baked tangent frame. Transform
        # the object matrix so the exporter rotates its split normals as well.
        if kind.startswith("dockyard"):
            rotation = Matrix.Rotation(-math.pi / 2, 4, "Z")
            scale = .293
        elif kind.startswith("naval_base"):
            rotation = Matrix.Identity(4)
            scale = PORT_SCALE
        else:
            rotation = Matrix.Identity(4)
            scale = .351 if kind.startswith("air_base") else .325
        obj.matrix_world = Matrix.Translation(Vector(map_point(kind, (0, 0, 0)))) @ rotation @ Matrix.Scale(scale, 4)
        obj.data.materials.clear()
        obj.data.polygons.foreach_set("material_index", [0] * len(obj.data.polygons))
        textures = files(kind)[1:]
        obj.data.materials.append(pdx.create_shader(SimpleNamespace(shader=["PdxMeshAdvancedSnow"],
                                  diff=[textures[0]], n=[textures[1]], spec=[textures[2]]), name(kind), str(stage)))
        dest = stage / files(kind)[0]
        pdx.export_meshfile(str(dest), exp_selected=True, exp_skel=False, exp_locs=False)
        tree = pdx_data.read_meshfile(str(dest))
        part, = tree.find("object").findall("./*/mesh")
        pd = pdx_data.PDXData(part)
        assert pd.material.shader == ["PdxMeshAdvancedSnow"]
        assert [getattr(pd.material, key)[0] for key in ("diff", "n", "spec")] == textures
        assert len(pd.tri) == 3 * len(obj.data.polygons)
        count = len(pd.p) // 3
        assert len(pd.u0) == count * 2 and len(pd.ta) == count * 4 and len(pd.n) == count * 3
        assert min(pd.tri) >= 0 and max(pd.tri) < count < 65536
        assert all(math.isfinite(v) for v in pd.p + pd.u0 + pd.n + pd.ta)
        assert min(pd.u0) >= -.00001 and max(pd.u0) <= 1.00001
        limits = [(min(pd.p[i::3]), max(pd.p[i::3])) for i in range(3)]
        for i in range(0, len(pd.tri), 3):
            a, b, c = (Vector(pd.p[3*j:3*j+3]) for j in pd.tri[i:i+3])
            assert (b-a).cross(c-a).length > 1e-12
        manifest[kind] = {"triangles": len(pd.tri)//3, "vertices": count, "native_bounds_xyz": limits}
    (stage / "models.json").write_text(json.dumps(manifest), encoding="utf-8")


def convert_textures(stage):
    from PIL import Image, ImageOps, ImageStat

    for kind in SCENES:
        def read(channel):
            return Image.open(stage / f"{name(kind)}_{channel}.png").convert("RGB")
        color = read("diffuse")
        assert min(ImageStat.Stat(color).stddev) > 4, f"Empty albedo bake: {kind}"
        nx, ny, _ = read("normal").split()
        smooth = ImageOps.invert(read("roughness").getchannel("R"))
        zero = Image.new("L", color.size, 0)
        # UnpackRRxGNormal reads X from green and negates alpha for Y.
        normal = Image.merge("RGBA", (nx, nx, zero, ImageOps.invert(ny)))
        spec = Image.merge("RGBA", (zero, smooth.point(lambda p: 30 + p//3), zero, smooth))
        for filename, image in zip(files(kind)[1:], (color.convert("RGBA"), normal, spec)):
            (stage / filename).write_bytes(dds_bytes(image))


def reimport(stage):
    import bpy
    from mathutils import Vector

    pdx = load_exporter()
    models = json.loads((stage / "models.json").read_text())
    for kind, record in models.items():
        bpy.ops.wm.read_factory_settings(use_empty=True)
        pdx.import_meshfile(str(stage / files(kind)[0]), imp_locs=False)
        mesh, = [o for o in bpy.context.scene.objects if o.type == "MESH"]
        mesh.data.calc_loop_triangles()
        assert len(mesh.data.loop_triangles) == record["triangles"]
        mat, = mesh.data.materials
        images = {node.image.name: node.image for node in mat.node_tree.nodes if node.type == "TEX_IMAGE"}
        assert set(images) == set(files(kind)[1:])
        assert all(tuple(image.size) == (SIZE, SIZE) for image in images.values())
        points = [mesh.matrix_world @ v.co for v in mesh.data.vertices]
        for axis, native in ((0, 0), (1, 2), (2, 1)):
            expected = record["native_bounds_xyz"][native]
            actual = (min(p[axis] for p in points), max(p[axis] for p in points))
            assert max(abs(a - b) for a, b in zip(actual, expected)) < 1e-5
        # Temporary studio proof of final DDS + reimported mesh, kept outside the mod.
        scene = bpy.context.scene
        scene.render.engine = "CYCLES"
        scene.cycles.samples = 8
        scene.render.resolution_x, scene.render.resolution_y = 420, 340
        scene.render.resolution_percentage = 100
        scene.world = bpy.data.worlds.new("Verification daylight")
        scene.world.color = (.45, .45, .45)
        center = Vector([(min(p[i] for p in points) + max(p[i] for p in points)) / 2 for i in range(3)])
        bpy.ops.object.light_add(type="SUN", rotation=(.5, -.5, -.3))
        bpy.context.object.data.energy = 2.4
        bpy.ops.object.camera_add(location=center + Vector((5, -8, 7)))
        cam = bpy.context.object
        cam.rotation_euler = (center-cam.location).to_track_quat("-Z", "Y").to_euler()
        cam.data.type = "ORTHO"
        cam.data.ortho_scale = 1.4 * max(hi-lo for lo, hi in record["native_bounds_xyz"])
        scene.camera = cam
        scene.render.filepath = str(stage / (kind + "_proof.png"))
        bpy.ops.render.render(write_still=True)


def apply(args):
    import shutil
    from PIL import Image

    before = input_hashes()
    executable = args.blender or os.environ.get("BLENDER_EXE") or "C:/Program Files/Blender Foundation/Blender 4.5/blender.exe"
    with tempfile.TemporaryDirectory(prefix="adiscord-map-facilities-") as directory:
        stage = Path(directory)
        # The exporter resolves image basenames while writing the mesh. These
        # staging images are replaced by the full bakes before native reimport.
        placeholder = dds_bytes(Image.new("RGBA", (4, 4), (128, 128, 128, 255)))
        for kind in SCENES:
            for filename in files(kind)[1:]:
                (stage / filename).write_bytes(placeholder)
        def run(mode):
            subprocess.run([executable, "--background", "--factory-startup", "--threads", "4",
                            "--python-exit-code", "1", "--python", str(Path(__file__).resolve()), "--",
                            mode, str(stage)], env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"), check=True)
        run("--export")
        convert_textures(stage)
        run("--reimport")
        if before != input_hashes():
            raise RuntimeError("Source files changed during export")
        hashes = {filename: digest(stage / filename) for k in SCENES for filename in files(k)}
        report = {"inputs": before, "files": hashes, "models": json.loads((stage / "models.json").read_text()),
                  "native_reimport": True, "hoi4_runtime_verified": False}
        (ROOT / DIRECTORY).mkdir(parents=True, exist_ok=True)
        for filename in hashes:
            shutil.copyfile(stage / filename, ROOT / DIRECTORY / filename)
        for path, body in sections().items():
            (ROOT / path).write_bytes(registry_bytes(path, body))
        (ROOT / REPORT).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        if args.proofs:
            args.proofs.mkdir(parents=True, exist_ok=True)
            for kind in SCENES:
                shutil.copyfile(stage / (kind + "_proof.png"), args.proofs / (kind + ".png"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--apply", action="store_true")
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--export", type=Path, help=argparse.SUPPRESS)
    modes.add_argument("--reimport", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--proofs", type=Path)
    parser.add_argument("--blender")
    args = parser.parse_args(sys.argv[sys.argv.index("--")+1:] if "--" in sys.argv else None)
    if args.export:
        write_meshes(args.export)
        return
    if args.reimport:
        reimport(args.reimport)
        return
    changes = stale()
    print(json.dumps({"stale": changes}, indent=2), flush=True)
    if args.apply and changes:
        apply(args)
        changes = stale()
    raise SystemExit(bool(changes))


if __name__ == "__main__":
    main()
