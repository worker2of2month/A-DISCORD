def load_province_adjacency(
    province_types: dict[int, str], color_to_province: dict[int, int]
) -> dict[int, set[int]]:
    """Read bitmap and special links into the province graph used by the engine."""
    adjacency = {province_id: set() for province_id in province_types}
    with Image.open(ROOT / "map" / "provinces.bmp") as source:
        image = source.convert("RGB")
        width, height = image.size
        red, green, blue = (band.tobytes() for band in image.split())

    previous_row = [-1] * width
    for y in range(height):
        row_start = y * width
        first = -1
        left = -1
        for x in range(width):
            offset = row_start + x
            color = (red[offset] << 16) | (green[offset] << 8) | blue[offset]
            try:
                province_id = color_to_province[color]
            except KeyError as exc:
                raise ValueError(
                    f"provinces.bmp uses undefined color {color >> 16};{(color >> 8) & 255};{color & 255} at {x},{y}"
                ) from exc
            if x == 0:
                first = province_id
            elif province_id != left:
                adjacency[province_id].add(left)
                adjacency[left].add(province_id)
            above = previous_row[x]
            if above != -1 and province_id != above:
                adjacency[province_id].add(above)
                adjacency[above].add(province_id)
            previous_row[x] = province_id
            left = province_id

        # Clausewitz maps wrap horizontally, so the two map edges are adjacent.
        if first != left:
            adjacency[first].add(left)
            adjacency[left].add(first)

    adjacency_path = ROOT / "map" / "adjacencies.csv"
    if adjacency_path.exists():
        with adjacency_path.open(encoding="utf-8-sig", newline="") as handle:
            for row in csv.reader(handle, delimiter=";"):
                if len(row) < 2 or not row[0].isdigit() or not row[1].isdigit():
                    continue
                first, second = int(row[0]), int(row[1])
                if first in adjacency and second in adjacency:
                    adjacency[first].add(second)
                    adjacency[second].add(first)
    return adjacency


def connected_components(nodes: set[int], adjacency: dict[int, set[int]]) -> list[set[int]]:
    remaining = set(nodes)
    components: list[set[int]] = []
    while remaining:
        start = min(remaining)
        component = {start}
        queue = deque((start,))
        remaining.remove(start)
        while queue:
            province_id = queue.popleft()
            for neighbour in adjacency[province_id]:
                if neighbour in remaining:
                    remaining.remove(neighbour)
                    component.add(neighbour)
                    queue.append(neighbour)
        components.append(component)
    return sorted(components, key=lambda component: (-len(component), min(component)))


def partition_connected_sea(
    sea: set[int],
    adjacency: dict[int, set[int]],
    positions: dict[int, tuple[float, float, float]],
) -> dict[int, set[int]]:
    """Partition one connected ocean with a seeded BFS, preserving connectivity."""
    seeds: dict[int, int] = {}
    for sea_region in SEA_REGIONS:
        candidates = [
            province_id
            for province_id in sea
            if sea_region_id_for(positions[province_id]) == sea_region.region_id
        ]
        if not candidates:
            raise ValueError(f"sea strategic region {sea_region.region_id} has no seed candidates")
        center_x = sum(positions[province_id][0] for province_id in candidates) / len(candidates)
        center_z = sum(positions[province_id][2] for province_id in candidates) / len(candidates)
        seeds[sea_region.region_id] = min(
            candidates,
            key=lambda province_id: (
                (positions[province_id][0] - center_x) ** 2 + (positions[province_id][2] - center_z) ** 2,
                province_id,
            ),
        )

    assignments = {province_id: region_id for region_id, province_id in seeds.items()}
    queue = deque(seeds[region_id] for region_id in sorted(seeds))
    while queue:
        province_id = queue.popleft()
        region_id = assignments[province_id]
        for neighbour in sorted(adjacency[province_id]):
            if neighbour in sea and neighbour not in assignments:
                assignments[neighbour] = region_id
                queue.append(neighbour)
    if set(assignments) != sea:
        raise ValueError("main ocean component could not be fully partitioned")

    partition = {region.region_id: set() for region in SEA_REGIONS}
    for province_id, region_id in assignments.items():
        partition[region_id].add(province_id)
    return partition


def load_province_positions() -> dict[int, tuple[float, float, float]]:
    positions: dict[int, tuple[float, float, float]] = {}
    with (ROOT / "map" / "unitstacks.txt").open(encoding="utf-8-sig", errors="strict") as handle:
        for line in handle:
            fields = line.strip().split(";")
            if len(fields) < 5 or not fields[0].isdigit() or fields[1] != "0":
                continue
            province_id = int(fields[0])
            positions.setdefault(province_id, (float(fields[2]), float(fields[3]), float(fields[4])))
    return positions


def format_provinces(provinces: set[int]) -> str:
    values = sorted(provinces)
    lines = []
    for start in range(0, len(values), 24):
        lines.append("\t\t" + " ".join(str(value) for value in values[start:start + 24]))
    return "\n".join(lines)


def format_weather(climate: str) -> str:
    lines = ["\tweather={"]
    for month, date_range in enumerate(MONTH_RANGES):
        low, high = TEMPERATURES[climate][month]
        clear, light, heavy, snow, blizzard, mud, sandstorm = phenomenon(climate, month)
        lines.extend((
            "\t\tperiod={",
            f"\t\t\tbetween={{ {date_range} }}",
            f"\t\t\ttemperature={{ {low:.1f} {high:.1f} }}",
            f"\t\t\tno_phenomenon={clear:.2f}",
            f"\t\t\train_light={light:.2f}",
            f"\t\t\train_heavy={heavy:.2f}",
            f"\t\t\tsnow={snow:.2f}",
            f"\t\t\tblizzard={blizzard:.2f}",
            f"\t\t\tarctic_water={arctic_water(climate, month):.2f}",
            f"\t\t\tmud={mud:.2f}",
            f"\t\t\tsandstorm={sandstorm:.2f}",
            "\t\t\tmin_snow_level=0.00",
            "\t\t}",
        ))
    lines.append("\t}")
    return "\n".join(lines)


def representative_positions(
    provinces: set[int], positions: dict[int, tuple[float, float, float]]
) -> list[tuple[float, float, float]]:
    available = [positions[province_id] for province_id in provinces if province_id in positions]
    if not available:
        raise ValueError("strategic region has no unit-stack positions")
    if len(available) == 1:
        return available

    x_span = max(point[0] for point in available) - min(point[0] for point in available)
    z_span = max(point[2] for point in available) - min(point[2] for point in available)
    axis = 0 if x_span >= z_span else 2
    ordered = sorted(available, key=lambda point: point[axis])
    if len(available) < 24:
        return [ordered[len(ordered) // 2]]
    return [ordered[len(ordered) // 3], ordered[(2 * len(ordered)) // 3]]


def sea_region_id_for(position: tuple[float, float, float]) -> int:
    x, _height, z = position
    latitude_band = 0 if z >= 1600 else 1 if z >= 1250 else 2 if z >= 900 else 3 if z >= 550 else 4
    longitude_band = 0 if x < 1800 else 1 if x < 3800 else 2
    return SEA_REGION_GRID[latitude_band][longitude_band]


def validate_manifest(states: dict[int, set[int]]) -> None:
    assigned: dict[int, int] = {}
    for region in REGIONS:
        if region.climate not in TEMPERATURES:
            raise ValueError(f"region {region.region_id} uses unknown climate {region.climate}")
        for state_id in region.states:
            if state_id not in states:
                raise ValueError(f"region {region.region_id} references missing state {state_id}")
            if state_id in assigned:
                raise ValueError(f"state {state_id} is in regions {assigned[state_id]} and {region.region_id}")
            assigned[state_id] = region.region_id
    missing = sorted(set(states) - set(assigned))
    if missing:
        raise ValueError(f"states without a strategic region: {missing}")


def build() -> None:
    states = load_states()
    validate_manifest(states)
    province_types, color_to_province = load_province_definitions()
    non_sea = {province_id for province_id, province_type in province_types.items() if province_type != "sea"}
    sea = {province_id for province_id, province_type in province_types.items() if province_type == "sea"}
    state_provinces = set().union(*states.values())
    unknown = state_provinces - non_sea
    if unknown:
        raise ValueError(f"state provinces absent from non-sea definition rows: {sorted(unknown)}")

    for path in REGION_DIR.glob("*.txt"):
        text = path.read_text(encoding="utf-8-sig", errors="strict")
        if path.name in ("1-sea.txt", "2-land.txt") or text.startswith(GENERATED_MARKER):
            path.unlink()

    province_positions = load_province_positions()
    for province_id in sea:
        if province_id not in province_positions:
            raise ValueError(f"sea province {province_id} has no unit-stack position")

    adjacency = load_province_adjacency(province_types, color_to_province)
    sea_components = connected_components(sea, adjacency)
    if not sea_components:
        raise ValueError("map contains no sea provinces")
    main_ocean = sea_components[0]

    region_provinces: dict[int, set[int]] = {}
    land_region_by_province: dict[int, int] = {}
    for region in REGIONS:
        provinces = set().union(*(states[state_id] for state_id in region.states))
        if region.region_id == 2:
            provinces |= non_sea - state_provinces
        region_provinces[region.region_id] = provinces
        for province_id in provinces:
            land_region_by_province[province_id] = region.region_id

    # Inland lakes must belong to their surrounding land region. Combining them
    # with the ocean makes Clausewitz report a fractioned naval strategic region.
    for component in sea_components[1:]:
        neighbouring_land = Counter(
            land_region_by_province[neighbour]
            for province_id in component
            for neighbour in adjacency[province_id]
            if neighbour in land_region_by_province
        )
        if not neighbouring_land:
            raise ValueError(f"isolated sea component {sorted(component)} has no neighbouring land region")
        region_id = min(neighbouring_land, key=lambda candidate: (-neighbouring_land[candidate], candidate))
        region_provinces[region_id].update(component)

    region_provinces.update(partition_connected_sea(main_ocean, adjacency, province_positions))

    sea_by_id = {region.region_id: region for region in SEA_REGIONS}
    for region_id, region in sorted(sea_by_id.items()):
        provinces = region_provinces.get(region_id, set())
        if not provinces:
            raise ValueError(f"sea strategic region {region_id} is empty")
        content = (
            f"{GENERATED_MARKER}\n"
            "strategic_region={\n"
            f"\tid={region.region_id}\n"
            f"\tname=\"STRATEGICREGION_{region.region_id}\"\n"
            "\tprovinces={\n"
            f"{format_provinces(provinces)}\n"
            "\t}\n"
            "\tnaval_terrain=water_deep_ocean\n"
            f"{format_weather(region.climate)}\n"
            "}\n"
        )
        path = REGION_DIR / f"{region.region_id}-{region.slug}.txt"
        path.write_text(content, encoding="utf-8", newline="\n")

    for region in REGIONS:
        provinces = region_provinces[region.region_id]
        content = (
            f"{GENERATED_MARKER}\n"
            "strategic_region={\n"
            f"\tid={region.region_id}\n"
            f"\tname=\"STRATEGICREGION_{region.region_id}\"\n"
            "\tprovinces={\n"
            f"{format_provinces(provinces)}\n"
            "\t}\n"
            f"{format_weather(region.climate)}\n"
            "}\n"
        )
        path = REGION_DIR / f"{region.region_id}-{region.slug}.txt"
        path.write_text(content, encoding="utf-8", newline="\n")

    LOCALISATION.parent.mkdir(parents=True, exist_ok=True)
    localisation_lines = ["\ufeffl_russian:"]
    for region in sorted((*SEA_REGIONS, *REGIONS), key=lambda item: item.region_id):
        localisation_lines.append(f' STRATEGICREGION_{region.region_id}: "{region.russian_name}"')
    LOCALISATION.write_text("\n".join(localisation_lines) + "\n", encoding="utf-8", newline="\n")

    weather_lines = []
    for region_id in sorted(region_provinces):
        size = "big" if len(region_provinces[region_id]) >= 100 else "small"
        for x, height, z in representative_positions(region_provinces[region_id], province_positions):
            weather_lines.append(f"{region_id};{x:.2f};{height:.2f};{z:.2f};{size}")
    WEATHER_POSITIONS.write_text("\n".join(weather_lines) + "\n", encoding="utf-8", newline="\n")

    print(f"Built {len(REGIONS)} land and {len(SEA_REGIONS)} sea strategic regions for {len(states)} states.")


if __name__ == "__main__":
    build()
