def arctic_water(climate: str, month: int) -> float:
    if climate == "polar_ocean":
        return 0.70 if month in (11, 0, 1) else 0.35 if month in (2, 3, 9, 10) else 0.08
    if climate == "subpolar_ocean":
        return 0.25 if month in (11, 0, 1) else 0.05 if month in (2, 10) else 0.0
    return 0.0


def load_states() -> dict[int, set[int]]:
    states: dict[int, set[int]] = {}
    for path in STATE_DIR.glob("*.txt"):
        text = path.read_text(encoding="utf-8-sig", errors="strict")
        state_match = re.search(r"\bid\s*=\s*(\d+)", text)
        province_match = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", text, re.DOTALL)
        if not state_match or not province_match:
            continue
        state_id = int(state_match.group(1))
        if state_id in states:
            raise ValueError(f"duplicate state id {state_id}")
        states[state_id] = {int(value) for value in re.findall(r"\d+", province_match.group(1))}
    return states


def load_province_definitions() -> tuple[dict[int, str], dict[int, int]]:
    provinces: dict[int, str] = {}
    colors: dict[int, int] = {}
    with (ROOT / "map" / "definition.csv").open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.reader(handle, delimiter=";"):
            if len(row) >= 5 and row[0].isdigit() and int(row[0]) > 0:
                province_id = int(row[0])
                provinces[province_id] = row[4]
                color = (int(row[1]) << 16) | (int(row[2]) << 8) | int(row[3])
                if color in colors:
                    raise ValueError(f"duplicate province color in definition.csv: {row[1:4]}")
                colors[color] = province_id
    return provinces, colors


