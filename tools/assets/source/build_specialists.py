def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def named(text, kind, name):
    return next(block for block in blocks(text, kind)
                if re.search(r'\bname\s*=\s*"' + re.escape(name) + '"', block))


def remove_body_island(body, points):
    """Keep native split normals when removing a detached clothing accessory."""
    import bmesh

    def corner_key(face, index):
        vertex = body.data.vertices[body.data.loops[index].vertex_index]
        return (tuple(round(c, 5) for c in vertex.co),
                tuple(round(c, 5) for c in body.data.uv_layers.active.data[index].uv),
                tuple(round(c, 5) for c in face.center))

    normals = {corner_key(face, index): tuple(body.data.corner_normals[index].vector)
               for face in body.data.polygons for index in face.loop_indices}
    bm = bmesh.new()
    bm.from_mesh(body.data)
    bmesh.ops.delete(bm, geom=[vertex for vertex in bm.verts
                              if tuple(round(c, 4) for c in vertex.co) in points], context='VERTS')
    bm.to_mesh(body.data)
    bm.free()
    body.data.normals_split_custom_set([
        normals[corner_key(face, index)]
        for face in body.data.polygons for index in face.loop_indices
    ])


def bindings():
    result = {}
    for relative, kind, source in (
        ('gfx/entities/ADISCORD_specialists.gfx', 'pdxmesh', 'ADISCORD_STP_marine_mesh'),
        ('gfx/entities/zzz_ADISCORD_specialists.asset', 'entity', 'ADISCORD_STP_marine_entity'),
    ):
        text = (ROOT / relative).read_text(encoding='utf-8')
        text = re.sub(re.escape(START) + '.*?' + re.escape(END), '', text, flags=re.S).rstrip()
        block = named(text, kind, source)
        # Idle clips retain their original skeleton; only the mesh is national.
        block = block.replace(source, source.replace('STP', 'NAM'))
        block = block.replace('STP_marine.mesh', 'NAM_marine.mesh')
        block = block.replace('pdxmesh = "ADISCORD_STP_marine_mesh"',
                              'pdxmesh = "ADISCORD_NAM_marine_mesh"')
        if kind == 'pdxmesh':
            block = 'objectTypes = {\n\t' + block + '\n}'
        else:
            aliases = []
            for tag in TAGS['NAM']:
                for role in ('marines', 'ADISCORD_marine_infantry'):
                    aliases.append('\n'.join((
                        'entity = {', '\tclone = "ADISCORD_NAM_marine_entity"',
                        f'\tname = "{tag}_{role}_entity"', '}',
                    )))
            block += '\n\n' + '\n\n'.join(aliases)
        result[Path(relative)] = (text + '\n\n' + START + block + '\n' + END).encode()
    pool = '\n'.join((
        '# Generated by tools/assets/source/build_specialists.py',
        'NAM = {', '\tinfantry_equipment = {', '\t\tpool = {',
        '\t\t\tsub_units = { ADISCORD_marine_infantry }', '\t\t\tweight = 3000',
        '\t\t\tmodels = { ADISCORD_NAM_marine_entity }', '\t\t}', '\t}', '}', '',
    ))
    result[Path('gfx/interface/equipmentdesigner/graphic_db/ADISCORD_specialists.txt')] = pool.encode()
    return result


def build(output):
    import bmesh
    import bpy
    from types import SimpleNamespace
    from infantry_polish import bake_diffuse, cloth_bag, uniform_material
    from mathutils import Vector

    pdx, _ = pdx_tools()
    output.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    pdx.import_meshfile(str(DONOR), imp_locs=False, join_materials=False)
    objects = [obj for obj in bpy.context.scene.objects if obj.type == 'MESH']
    body = next(obj for obj in objects if any(
        'body' in node.image.name for mat in obj.data.materials
        for node in mat.node_tree.nodes if node.type == 'TEX_IMAGE' and node.image
    ))
    gear = next(obj for obj in objects if obj != body)
    jacket = uniform_material(body, (.30, .38, .42), 'NAM naval landing')
    nodes, links = jacket.node_tree.nodes, jacket.node_tree.links
    shader = nodes.get('Principled BSDF')
    original = shader.inputs['Base Color'].links[0].from_socket
    gray = nodes.new('ShaderNodeRGBToBW')
    links.new(original, gray.inputs[0])
    cloth = nodes.new('ShaderNodeValToRGB')
    cloth.color_ramp.elements[0].position = .015
    cloth.color_ramp.elements[0].color = (.018, .027, .031, 1)
    cloth.color_ramp.elements[1].position = .16
    cloth.color_ramp.elements[1].color = (.075, .095, .105, 1)
    links.new(gray.outputs[0], cloth.inputs[0])
    links.new(cloth.outputs[0], shader.inputs['Base Color'])
    body_keys = [tuple(round(c, 4) for c in vertex.co) for vertex in body.data.vertices]
    body_links = {key: set() for key in body_keys}
    for face in body.data.polygons:
        for a, b in zip(face.vertices, (*face.vertices[1:], face.vertices[0])):
            body_links[body_keys[a]].add(body_keys[b])
            body_links[body_keys[b]].add(body_keys[a])
    remaining, jacket_islands, chinstrap_islands = set(body_keys), [], []
    while remaining:
        first = remaining.pop()
        component, pending = {first}, [first]
        while pending:
            for key in body_links[pending.pop()]:
                if key in remaining:
                    remaining.remove(key)
                    component.add(key)
                    pending.append(key)
        low, high = min(point[2] for point in component), max(point[2] for point in component)
        if 3.2 < low < 3.5 and 6.4 < high < 6.7:
            jacket_islands.append(component)
        if (6.25 < low < 6.35 and 6.85 < high < 7.0
                and max(p[0] for p in component) - min(p[0] for p in component) < .7
                and min(p[1] for p in component) > -.4):
            chinstrap_islands.append(component)
    assert len(jacket_islands) == 1, 'NAM tunic island changed'
    for face in body.data.polygons:
        face.material_index = len(body.data.materials) - 1 if body_keys[face.vertices[0]] in jacket_islands[0] else 0
    assert len(chinstrap_islands) == 1 and len(chinstrap_islands[0]) == 68
    remove_body_island(body, chinstrap_islands[0])
    # Replace complete helmet islands, retaining the NAM face and field kit.
    keys = [tuple(round(c, 4) for c in vertex.co) for vertex in gear.data.vertices]
    adjacent = {key: set() for key in keys}
    for face in gear.data.polygons:
        for a, b in zip(face.vertices, (*face.vertices[1:], face.vertices[0])):
            adjacent[keys[a]].add(keys[b])
            adjacent[keys[b]].add(keys[a])
    remaining, helmet = set(keys), set()
    while remaining:
        first = remaining.pop()
        component, pending = {first}, [first]
        while pending:
            for key in adjacent[pending.pop()]:
                if key in remaining:
                    remaining.remove(key)
                    component.add(key)
                    pending.append(key)
        if max(point[2] for point in component) > 6.8:
            helmet.update(component)
    assert helmet, 'NAM helmet geometry not found'
    bm = bmesh.new()
    bm.from_mesh(gear.data)
    bmesh.ops.delete(bm, geom=[vertex for vertex in bm.verts
                              if tuple(round(c, 4) for c in vertex.co) in helmet], context='VERTS')
    bm.to_mesh(gear.data)
    bm.free()
    for mat in gear.data.materials:
        shader = mat.node_tree.nodes.get('Principled BSDF')
        nodes, links = mat.node_tree.nodes, mat.node_tree.links
        tint = nodes.new('ShaderNodeMixRGB')
        tint.blend_type = 'MULTIPLY'
        tint.inputs[0].default_value = 1
        tint.inputs[2].default_value = (.25, .34, .31, 1)
        links.new(shader.inputs['Base Color'].links[0].from_socket, tint.inputs[1])
        links.new(tint.outputs[0], shader.inputs['Base Color'])
    rig = next(mod.object for mod in gear.modifiers if mod.type == 'ARMATURE')
    additions = []

    def material(label, color):
        mat = bpy.data.materials.new(label)
        mat.use_nodes = True
        mat.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value = (*color, 1)
        mat.node_tree.nodes['Principled BSDF'].inputs['Roughness'].default_value = .82
        return mat

    brass = material('NAM naval brass', (.58, .38, .13))
    flotation = material('NAM flotation canvas', (.080, .105, .090))
    rubber = material('NAM sealed canvas', (.035, .055, .043))
    beret = material('NAM black marine wool', (.018, .023, .025))

    def mesh(label, vertices, faces, mat, bone='back_mid'):
        data = bpy.data.meshes.new(label)
        data.from_pydata(vertices, [], faces)
        data.update()
        obj = bpy.data.objects.new(label, data)
        bpy.context.scene.collection.objects.link(obj)
        data.materials.append(mat)
        obj.vertex_groups.new(name=bone).add(list(range(len(vertices))), 1, 'REPLACE')
        obj.modifiers.new('Marine rig', 'ARMATURE').object = rig
        additions.append(obj)
        return obj

    # The wool folds over a narrow band and drops to the wearer's right.
    rows = ((.39, .445, 7.02, 0, 0), (.397, .452, 7.055, 0, 0),
            (.40, .44, 7.11, -.005, .02), (.49, .46, 7.22, -.065, .15),
            (.35, .37, 7.31, .005, .05), (.17, .18, 7.34, .015, 0),
            (.025, .025, 7.345, .02, 0))
    vertices = [(rx * math.cos(angle) + lean, ry * math.sin(angle) - .035,
                 z - drop * max(0, -math.cos(angle)))
                for rx, ry, z, lean, drop in rows
                for angle in (math.tau * i / 32 for i in range(32))]
    faces = [(r * 32 + i, r * 32 + (i + 1) % 32,
              (r + 1) * 32 + (i + 1) % 32, (r + 1) * 32 + i)
             for r in range(len(rows) - 1) for i in range(32)]
    faces.append(tuple(range((len(rows) - 1) * 32, len(rows) * 32)))
    cap = mesh('Marine beret', vertices, faces, beret, 'head')
    cap.data.materials.append(material('Beret leather band', (.008, .010, .010)))
    for face in cap.data.polygons:
        face.use_smooth = True
        face.material_index = int(face.index < 32)
    bpy.context.view_layer.objects.active = cap
    fold = cap.modifiers.new('Rounded wool fold', 'SUBSURF')
    fold.levels = 1
    bpy.ops.object.modifier_apply(modifier=fold.name)
    # A small anchor is modelled on the beret face, separate from the national diamond.
    anchor = [(-.018, -.486, 7.16), (.018, -.486, 7.16), (.018, -.486, 7.04),
              (.075, -.486, 7.09), (.055, -.486, 7.025), (0, -.486, 6.99),
              (-.055, -.486, 7.025), (-.075, -.486, 7.09), (-.018, -.486, 7.04)]
    from mathutils.bvhtree import BVHTree

    cap_surface = BVHTree.FromPolygons([vertex.co for vertex in cap.data.vertices],
                                       [list(face.vertices) for face in cap.data.polygons])
    for vertex in body.data.vertices:
        if vertex.co.z > 7.0 and abs(vertex.co.x) < .5:
            cover, _, _, _ = cap_surface.ray_cast(vertex.co + Vector((0, 0, .005)), Vector((0, 0, 1)), 1)
            assert cover is not None, ('Exposed scalp', tuple(vertex.co))

    def cap_badge(name, outline):
        fitted = []
        for x, _, z in outline:
            x += .13
            z = 7.08 + (z - 6.99) * .8
            point, normal, _, _ = cap_surface.ray_cast(Vector((x, -3, z)), Vector((0, 1, 0)), 6)
            assert point is not None, (name, x, z)
            fitted.append(tuple(point + normal * .009))
        mesh(name, fitted, [tuple(reversed(range(len(fitted))))], brass, 'head')

    cap_badge('Marine anchor', anchor)
    cap_badge('Anchor crossbar', [(-.055, -.489, 7.13), (.055, -.489, 7.13),
                                 (.055, -.489, 7.115), (-.055, -.489, 7.115)])
    # A shallow U-shaped collar distinguishes landing troops without doubling their kit.
    points = [(-.41, -.53, 5.05), (-.49, -.55, 5.55), (-.47, -.37, 5.96),
              (-.36, .06, 6.08), (0, .35, 6.11), (.36, .06, 6.08),
              (.47, -.37, 5.96), (.49, -.55, 5.55), (.41, -.53, 5.05)]
    vertices = []
    for i, point in enumerate(points):
        axis = (Vector(points[min(i + 1, len(points) - 1)]) - Vector(points[max(0, i - 1)])).normalized()
        u = axis.cross(Vector((0, 1, 0))).normalized()
        v = axis.cross(u).normalized()
        for j in range(8):
            angle = math.tau * j / 8
            vertices.append(tuple(Vector(point) + .115 * (u * math.cos(angle) + v * math.sin(angle))))
    faces = [(i * 8 + j, i * 8 + (j + 1) % 8,
              (i + 1) * 8 + (j + 1) % 8, (i + 1) * 8 + j)
             for i in range(len(points) - 1) for j in range(8)]
    faces.extend((tuple(reversed(range(8))), tuple(range(64, 72))))
    collar = mesh('Landing flotation collar', vertices, faces, flotation)
    for face in collar.data.polygons:
        face.use_smooth = True
    for part, kind, vertices, faces in cloth_bag(.52, .25, .62):
        mesh('Sealed landing bag ' + part,
             [(x + .61, y + .37, z + 4.03) for x, y, z in vertices],
             faces, flotation if kind == 'canvas' else rubber, 'Hip')
    # Preserve the source UV lookup while baking the combined equipment atlas.
    for mat in gear.data.materials:
        nodes, links = mat.node_tree.nodes, mat.node_tree.links
        uv = nodes.new('ShaderNodeUVMap')
        uv.uv_map = gear.data.uv_layers.active.name
        for node in list(nodes):
            if node.type == 'TEX_IMAGE' and not node.inputs['Vector'].is_linked:
                links.new(uv.outputs['UV'], node.inputs['Vector'])
    bpy.ops.object.select_all(action='DESELECT')
    gear.select_set(True)
    for obj in additions:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = gear
    bpy.ops.object.join()
    atlas = gear.data.uv_layers.new(name='NavalEquipmentAtlas')
    gear.data.uv_layers.active = atlas
    atlas.active_render = True
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(island_margin=.008)
    bpy.ops.object.mode_set(mode='OBJECT')
    for obj, part in ((body, 'body'), (gear, 'gear')):
        obj.name = f'{NAME}_{part}'
        bake_diffuse(obj, output / f'{NAME}_{part}.png', f'{NAME}_{part}')
    bpy.ops.file.pack_all()
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.wm.save_as_mainfile(filepath=str(output / f'{NAME}.blend'))
    # The native exporter writes UV layers in collection order; u0 must be the bake atlas.
    for layer in list(gear.data.uv_layers):
        if layer.name != 'NavalEquipmentAtlas':
            gear.data.uv_layers.remove(layer)
    # Python packaging converts the baked maps to mipmapped DDS before verification.
    for obj, part in ((body, 'body'), (gear, 'gear')):
        if part == 'gear':
            bm = bmesh.new()
            bm.from_mesh(obj.data)
            bmesh.ops.triangulate(bm, faces=list(bm.faces))
            bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
            bm.to_mesh(obj.data)
            bm.free()
        (output / f'{NAME}_{part}_diffuse.dds').write_bytes(
            (output / f'{NAME}_{part}.png').read_bytes()
        )
        for channel in ('normal', 'specular'):
            (output / f'{NAME}_{part}_{channel}.dds').write_bytes(
                (DONOR.parent / f'NAM_field_{part}_{channel}.dds').read_bytes()
            )
        material = pdx.create_shader(SimpleNamespace(
            shader=['PdxMeshAdvanced'], diff=[f'{NAME}_{part}_diffuse.dds'],
            n=[f'{NAME}_{part}_normal.dds'], spec=[f'{NAME}_{part}_specular.dds'],
        ), f'{NAME}_{part}', str(output))
        obj.data.materials.clear()
        obj.data.materials.append(material)
        for face in obj.data.polygons:
            face.material_index = 0
    bpy.ops.object.select_all(action='DESELECT')
    for obj in objects:
        obj.select_set(True)
    path = output / f'{NAME}.mesh'
    pdx.export_meshfile(str(path), exp_selected=True, exp_locs=False)
    data, donor = path.read_bytes(), DONOR.read_bytes()
    marker = b'[locator\0'
    assert data.count(marker) == donor.count(marker) == 1
    path.write_bytes(data[:data.index(marker)] + donor[donor.index(marker):])
    finalize_mesh(path)
    (output / 'build_source.sha256').write_text(digest(Path(__file__)))


def files(output):
    from PIL import Image

    result = bindings()
    for path in sorted(output.glob(f'{NAME}*')):
        if path.suffix in ('.mesh', '.dds'):
            result[DEST / path.name] = path.read_bytes()
    for part in ('body', 'gear'):
        result[DEST / f'{NAME}_{part}_diffuse.dds'] = dds(Image.open(output / f'{NAME}_{part}.png'))
    result[DEST / f'{NAME}_gear_normal.dds'] = dds(Image.new('RGBA', (512, 512), (255, 128, 0, 128)), True)
    result[DEST / f'{NAME}_gear_specular.dds'] = dds(Image.new('RGBA', (512, 512), (0, 48, 0, 36)), True)
    result[Path('tools/assets/source') / f'{NAME}.blend'] = (output / f'{NAME}.blend').read_bytes()
    if (output / 'verification.json').is_file():
        result[REPORT] = (output / 'verification.json').read_bytes()
    return result


def package(output, apply=False, check=False):
    content = files(output)
    if apply:
        report = json.loads((output / 'verification.json').read_text())
        assert report['generator_sha256'] == digest(Path(__file__))
        for path, data in content.items():
            if path.parent == DEST:
                assert report['files'][path.name] == hashlib.sha256(data).hexdigest()
    changed = [str(path) for path, data in content.items()
               if not (ROOT / path).is_file() or (ROOT / path).read_bytes() != data]
    if not check:
        destination = ROOT if apply else output / 'package'
        for path, data in content.items():
            target = destination / path
            if not target.is_file() or target.read_bytes() != data:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
    print(json.dumps({'changed': changed, 'applied': apply}, indent=2))
    if check and changed:
        raise SystemExit(1)


def verify(output):
    import bpy
    from mathutils import Vector
    from build_northern_infantry import native_animation_frames, apply_native_pose

    pdx, pdx_data = pdx_tools()
    assert (output / 'build_source.sha256').read_text() == digest(Path(__file__))
    from build_crimson_sentinel import configure_preview_materials
    directory = output / 'package' / DEST
    path = directory / f'{NAME}.mesh'
    tree = pdx_data.read_meshfile(str(path))
    donor = pdx_data.read_meshfile(str(DONOR))
    assert [(loc.tag, loc.attrib) for loc in tree.find('locator')] == [
        (loc.tag, loc.attrib) for loc in donor.find('locator')
    ]
    source_body = pdx_data.PDXData(donor.find('object')[0].find('mesh'))
    exported_body = pdx_data.PDXData(tree.find('object')[0].find('mesh'))
    assert len(exported_body.tri) // 3 == len(source_body.tri) // 3 - 96 == 2367
    source_normals = {}
    for index in range(len(source_body.p) // 3):
        position = tuple(round(v, 3) for v in source_body.p[index * 3:index * 3 + 3])
        source_normals.setdefault(position, []).append(source_body.n[index * 3:index * 3 + 3])
    normal_delta = 0
    for index in range(len(exported_body.p) // 3):
        position = tuple(round(v, 3) for v in exported_body.p[index * 3:index * 3 + 3])
        normal = exported_body.n[index * 3:index * 3 + 3]
        delta = min(max(abs(a - b) for a, b in zip(normal, source))
                    for source in source_normals[position])
        normal_delta = max(normal_delta, delta)
    assert normal_delta < .002, ('Changed NAM body normals', normal_delta)
    triangles = 0
    for shape in tree.find('object'):
        bones = list(shape.find('skeleton'))
        donor_bones = list(next(s.find('skeleton') for s in donor.find('object')
                                if s.find('skeleton') is not None))
        assert [bone.tag for bone in bones] == [bone.tag for bone in donor_bones]
        for bone, original in zip(bones, donor_bones):
            assert bone.attrib.get('pa') == original.attrib.get('pa')
            assert max(abs(a - b) for a, b in zip(bone.attrib['tx'], original.attrib['tx'])) < .001
        for mesh in shape.findall('mesh'):
            data = pdx_data.PDXData(mesh)
            assert 'u1' not in mesh.attrib, 'Native u0 must contain the baked equipment atlas'
            count = len(data.p) // 3
            assert all(math.isfinite(v) for v in data.p + data.n + data.u0)
            assert max(data.tri) < count and min(data.tri) >= 0
            stride = data.skin.bones[0]
            assert len(data.skin.w) == len(data.skin.ix) == count * stride
            assert all(0 <= index < len(bones) for index in data.skin.ix)
            for i in range(count):
                assert abs(sum(data.skin.w[i * stride:(i + 1) * stride]) - 1) < .001
            triangles += len(data.tri) // 3
    bpy.ops.wm.read_factory_settings(use_empty=True)
    pdx.import_meshfile(str(path), imp_locs=True, join_materials=False)
    objects = [obj for obj in bpy.context.scene.objects if obj.type == 'MESH']
    rigs = [obj for obj in bpy.context.scene.objects if obj.type == 'ARMATURE']
    before = set(bpy.context.scene.objects)
    pdx.import_meshfile(str(ROOT / 'gfx/models/units/ADISCORD_weapons/infantry_1.mesh'),
                        imp_skel=False, imp_locs=False)
    weapons = []
    for obj in set(bpy.context.scene.objects) - before:
        if obj.type != 'MESH':
            continue
        for index, bone in enumerate(('Right_Hand_node', 'Left_Hand_node', 'mid_back_node', 'Root_node_2')):
            copy = obj if index == 0 else obj.copy()
            if index:
                bpy.context.scene.collection.objects.link(copy)
            weapons.append((copy, bone))
    configure_preview_materials()

    def place_weapons():
        for obj, bone in weapons:
            transform = rigs[0].pose.bones[bone].matrix
            obj.matrix_world = rigs[0].matrix_world @ transform
            obj.hide_render = max(abs(value) for value in transform.to_scale()) < .001

    scene = bpy.context.scene
    scene.render.engine = 'CYCLES'
    scene.cycles.samples = 24
    scene.cycles.use_denoising = True
    scene.render.resolution_x, scene.render.resolution_y = 800, 1000
    scene.render.resolution_percentage = 100
    scene.world = bpy.data.worlds.new('Naval studio')
    scene.world.use_nodes = True
