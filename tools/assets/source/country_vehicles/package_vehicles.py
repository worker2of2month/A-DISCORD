"""Generate the shared native vehicle registries; --check precedes --apply.

Aircraft geometry and textures are packaged by build_country_aircraft.
Existing country vehicles retain their own mesh exports and animations.
"""

import argparse
import json
from pathlib import Path
import re
import sys


MOD = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(MOD))
from tools.assets.source.country_vehicles.tank_designs import CLASSES, DESIGNS, TANK_EQUIPMENT, model_name

DEST = MOD / "gfx/models/units/ADISCORD_country_vehicles"
HEADER = "# Generated by tools/assets/source/country_vehicles/package_vehicles.py\n"
TAGS = ("VAL", "NOD", "STP")
FAMILIES = ("DEF", "ARB", "WRK", "RUS", "NAM", "SHL")
PREFIXES = ("early_", "", "future_")
ARAB_TAGS = ("SHL", "AZH", "GLP", "KDR", "KYZ", "MZR", "RHM", "SDR", "SLF")
VORKERLAND_TAGS = (
    "WRK", "DAN", "EYR", "EGC", "RIV", "YOR", "ZAO", "PWR", "VLA",
    "ROM", "SOL", "TRU", "WCG", "VAD", "WKR", "TVA", "IBA",
)
EXISTING_AIR = {"VAL": "VAL", "NOD": "NOD", "STP": "NOD", "STS": "STP", "SRP": "STP"}
NAMES = tuple(f"{tag}_{role}" for tag in TAGS for role in ("tank", "fighter", "cas"))
NAMES += tuple(f"{tag}_{prefix}{role}" for tag in TAGS for prefix in ("early_", "future_")
               for role in ("fighter", "cas"))
SHARED_NAMES = tuple(f"{family}_{prefix}{role}" for family in FAMILIES
                     for prefix in PREFIXES for role in ("fighter", "cas"))
SPECIAL_NAMES = ("STS_taran", "SHL_tank")
APC_TAGS = ("VAL", "STP", "STS", "NAM", "NOD", "SHL")
ARTILLERY_TAGS = ("NAM", "STP", "VAL", "STS")
ARTILLERY_ROUTES = (
    "artillery", *[f"artillery_{level}" for level in range(4)],
    "ADISCORD_line_artillery", "artillery_equipment", "artillery_equipment_1",
    "ADISCORD_artillery_equipment_2160", "ADISCORD_artillery_equipment_2170",
    "ADISCORD_artillery_equipment_2183",
)
APC_ROUTES = (
    "mechanized", *[f"mechanized_{level}" for level in range(4)],
    "motorized", "motorized_0", "motorized_1", "motorized_equipment", "motorized_equipment_1",
    "ADISCORD_mechanized_infantry", "ADISCORD_armored_carrier_archetype",
    "ADISCORD_armored_carrier_2163", "ADISCORD_ifv_2170", "ADISCORD_networked_ifv_2183",
)


def apc_states(vehicle=False):
    text = ""
    for state, clip in (
        ("idle", "idle"), ("training", "idle"), ("death", "idle"),
        ("move", "move"), ("retreat", "move"),
        ("attack", "attack"), ("defend", "attack"), ("support_attack", "attack"),
    ):
        text += f'\tstate = {{\n\t\tname = "{state}"\n\t\tanimation = "{clip}"\n'
        # Muzzle particles start at time zero, so the aiming pose must be immediate.
        blend = "0.0" if clip == "attack" else "0.3"
        text += f'\t\tanimation_blend_time = {blend}\n\t\tanimation_speed = 1.0\n'
        if vehicle and clip == "move":
            for node in ("left_wheel", "right_wheel"):
                text += ('\t\tevent = {\n\t\t\ttime = 0\n'
                         f'\t\t\tnode = "{node}"\n'
                         '\t\t\tparticle = "tank_moving_tracks_particle"\n'
                         '\t\t\tkeep_particle = no\n\t\t\ttrigger_once = yes\n\t\t}\n')
            text += ('\t\tevent = {\n\t\t\ttrigger_once = yes\n'
                     '\t\t\tsound = { soundeffect = "motorized_unit_move_animation" }\n\t\t}\n')
        if vehicle and clip == "attack":
            text += ('\t\tevent = {\n\t\t\ttime = 0\n\t\t\tnode = "barrel"\n'
                     '\t\t\tparticle = "mechanized_attack_barrel_particle"\n'
                     '\t\t\tkeep_particle = yes\n\t\t}\n'
                     '\t\tevent = { sound = { soundeffect = "mechanized_units_mg_fire" } }\n')
        text += '\t}\n'
    return text


def apc_registry():
    gfx, assets, animations = "", "", ""
    for tag in APC_TAGS:
        name = f"{tag}_apc"
        gfx += (f'\tpdxmesh = {{\n\t\tname = "ADISCORD_{name}_mesh"\n'
                f'\t\tfile = "gfx/models/units/ADISCORD_country_vehicles/{name}.mesh"\n'
                '\t\tscale = 0.95\n')
        for clip in ("idle", "move", "attack"):
            gfx += f'\t\tanimation = {{ id = "{clip}" type = "ADISCORD_{name}_{clip}_animation" }}\n'
            animations += f'animation = {{ name = "ADISCORD_{name}_{clip}_animation" file = "{name}_{clip}.anim" }}\n'
        gfx += '\t}\n'
        assets += (f'\nentity = {{\n\tname = "ADISCORD_{name}_vehicle_entity"\n'
                   f'\tpdxmesh = "ADISCORD_{name}_mesh"\n\tdefault_state = "idle"\n'
                   + apc_states(vehicle=True) + '}\n')
        assets += (f'\nentity = {{\n\tclone = "{tag}_infantry_entity"\n'
                   f'\tname = "ADISCORD_{name}_escort_entity"\n}}\n')
        assets += (f'\nentity = {{\n\tname = "ADISCORD_{name}_entity"\n'
                   '\tpdxmesh = "motorized_frame_mesh"\n\tdefault_state = "idle"\n'
                   + apc_states()
                   + '\tattach = {\n\t\tname = "vehicle"\n'
                   + f'\t\tvehicle = "ADISCORD_{name}_vehicle_entity"\n\t}}\n'
                   + '\tattach = {\n\t\tname = "infantry"\n'
                   + f'\t\tinfantry = "ADISCORD_{name}_escort_entity"\n\t}}\n}}\n')
    for identity in country_families():
        tag = identity.split("_", 1)[0]
        if tag in APC_TAGS:
            assets += "\n"
            for route in APC_ROUTES:
                assets += alias(f"ADISCORD_{tag}_apc_entity", f"{identity}_{route}_entity")
    return gfx, assets, animations


def artillery_entities():
    """Use the native gun and frame with each country's infantry attachment."""
    assets = ""
    for tag in ARTILLERY_TAGS:
        name = f"{tag}_artillery"
        assets += (f'\nentity = {{\n\tname = "ADISCORD_{name}_entity"\n'
                   '\tpdxmesh = "frame_artillery_mesh"\n\tdefault_state = "idle"\n')
        for state, clip in (("idle", "idle"), ("training", "idle"), ("death", "idle"),
                            ("move", "move"), ("retreat", "move"), ("attack", "attack"),
                            ("defend", "attack"), ("support_attack", "attack")):
            blend = "0.0" if clip == "attack" else "0.3"
            assets += (f'\tstate = {{\n\t\tname = "{state}"\n\t\tanimation = "{clip}"\n'
                       f'\t\tanimation_blend_time = {blend}\n\t\tanimation_speed = 1.0\n')
            if clip == "attack":
                assets += '\t\tpropagate_state = { infantry = "idle" }\n'
            assets += '\t}\n'
        assets += ('\tattach = {\n\t\tname = "artillery"\n'
                   '\t\tartillery = "artillery_gun_entity"\n\t}\n'
                   '\tattach = {\n\t\tname = "infantry"\n'
                   f'\t\tinfantry = "{tag}_infantry_entity"\n\t}}\n}}\n')
    for identity in country_families():
        tag = identity.split("_", 1)[0]
        if tag in ARTILLERY_TAGS:
            assets += "\n"
            for route in ARTILLERY_ROUTES:
                assets += alias(f"ADISCORD_{tag}_artillery_entity", f"{identity}_{route}_entity")
    return assets


def apc_model_pools():
    """Keep national candidates scoped to the battalion and equipment family."""
    text = HEADER
    for tag in APC_TAGS:
        # Carrier queries use the equipment origin, including foreign designs.
        # Reusing this entity there also deduplicates the later rifle candidate
        # before the designer can assign its higher visual technology priority.
        text += (
            f"\n{tag} = {{\n"
            "\tinfantry_equipment = {\n"
            "\t\tpool = {\n"
            "\t\t\tsub_units = { ADISCORD_mechanized_infantry }\n"
            "\t\t\tweight = 3000\n"
            f"\t\t\tmodels = {{ ADISCORD_{tag}_apc_entity }}\n"
            "\t\t}\n"
            "\t}\n"
        )
        if tag in ARTILLERY_TAGS:
            text += ("\tartillery_equipment = {\n\t\tpool = {\n"
                     "\t\t\tsub_units = { artillery ADISCORD_line_artillery }\n"
                     "\t\t\tweight = 3000\n"
                     f"\t\t\tmodels = {{ ADISCORD_{tag}_artillery_entity }}\n"
                     "\t\t}\n\t}\n")
        text += "}\n"
    return text


def air_routes():
    routes = {}
    for role in ("fighter", "cas"):
        routes[f"ADISCORD_{role}"] = (role, 0)
        routes[f"ADISCORD_{role}_archetype"] = (role, 0)
        for level in range(4):
            routes[f"ADISCORD_{role}_{level}"] = (role, min(level, 2))
    equipment = {
        "fighter": (
            ("fighter_airframe_2163",),
            ("fighter_airframe_2161", "fighter_airframe_2166"),
            ("interceptor_airframe_2183", "fighter_airframe_2170", "fighter_airframe_2175"),
        ),
        "cas": (
            ("cas_airframe_2170",),
            ("attack_airframe_2163", "vtol_airframe_2170"),
            ("drone_airframe_2183", "attack_airframe_2170", "attack_airframe_2175"),
        ),
    }
    for role, tiers in equipment.items():
        for tier, names in enumerate(tiers):
            for name in names:
                routes[f"ADISCORD_{name}"] = (role, tier)
    return routes


def country_families():
    tags = set()
    for path in sorted((MOD / "common/country_tags").glob("*.txt")):
        tags.update(re.findall(r'^\s*([A-Z0-9]{3})\s*=\s*"', path.read_text(encoding="utf-8-sig"), re.M))
    regional = set(ARAB_TAGS) | set(VORKERLAND_TAGS) | {"RUS", "NAM"}
    if not regional <= tags:
        raise ValueError(f"Unregistered aircraft tags: {sorted(regional - tags)}")
    families = dict.fromkeys(sorted(tags), "DEF")
    families.update(dict.fromkeys(ARAB_TAGS, "ARB"))
    families.update(dict.fromkeys(VORKERLAND_TAGS, "WRK"))
    families.update(EXISTING_AIR)
    families.update({"RUS": "RUS", "NAM": "NAM", "SHL": "SHL"})
    # A cosmetic name takes priority over the real country in native entity lookup.
    for path in sorted((MOD / "common/countries").glob("*.txt")):
        for name in re.findall(r'^([A-Z][A-Za-z0-9_]+)\s*=\s*\{', path.read_text(encoding="utf-8-sig"), re.M):
            tag = name.split("_", 1)[0]
            if tag in families and "_" in name:
                families[name] = families[tag]
    # Confederation identities are also used directly from country history.
    for path in sorted((MOD / "history/countries").glob("*.txt")):
        for name in re.findall(r'\bset_cosmetic_tag\s*=\s*([A-Za-z0-9_]+)', path.read_text(encoding="utf-8-sig")):
            tag = name.split("_", 1)[0]
            if tag in families:
                families[name] = families[tag]
    return families


def alias(parent, name):
    # Death or Dishonor registers the tierless ROM aircraft at version zero.
    if name in ("ROM_light_plane_entity", "ROM_medium_plane_entity"):
        return (
            'entity = {\n'
            f'\tclone = "{parent}"\n'
            f'\tname = "{name}"\n'
            '\tversion = 1\n'
            '}\n'
        )
    return f'entity = {{ clone = "{parent}" name = "{name}" }}\n'


TANK_SUBUNITS = {
    "light": ("ADISCORD_light_tank", "ADISCORD_recon_platform"),
    "medium": ("ADISCORD_combat_platform",),
    "heavy": ("ADISCORD_heavy_platform",),
}


def tank_pool_registry():
    text = HEADER
    for tag in ("default", *DESIGNS):
        text += f"\n{tag} = {{\n"
        for kind in CLASSES:
            national = tag != "default"
            entity = f"ADISCORD_{model_name(tag, kind)}_entity" if national else f"{kind}_armor_entity"
            prefix = tag + "_" if national else ""
            for equipment in TANK_EQUIPMENT[kind]:
                text += (
                    f"\t{equipment} = {{\n\t\tpool = {{\n"
                    f"\t\t\tweight = {3000 if national else 1}\n"
                    f"\t\t\ticons = {{ GFX_{prefix}{equipment}_medium }}\n"
                    f"\t\t\tmodels = {{ {entity} }}\n"
                    "\t\t}\n\t}\n"
                )
        text += "}\n"
    return text


def tank_registry():
    gfx, assets, animations = "", "", ""
    for tag, designs in DESIGNS.items():
        for kind, design in zip(CLASSES, designs):
            if design is None:
                continue
            name = model_name(tag, kind)
            gfx += (f'\tpdxmesh = {{\n\t\tname = "ADISCORD_{name}_mesh"\n'
                    f'\t\tfile = "gfx/models/units/ADISCORD_country_vehicles/{name}.mesh"\n'
                    '\t\tscale = 0.55\n')
            for clip in ("idle", "move", "attack"):
                animation = f"ADISCORD_{name}_{clip}_animation"
                gfx += f'\t\tanimation = {{ id = "{clip}" type = "{animation}" }}\n'
                animations += f'animation = {{ name = "{animation}" file = "{name}_{clip}.anim" }}\n'
            gfx += "\t}\n"
            assets += (f'\nentity = {{\n\tclone = "{kind}_armor_entity"\n'
                       f'\tname = "ADISCORD_{name}_entity"\n'
                       f'\tpdxmesh = "ADISCORD_{name}_mesh"\n\tdefault_state = "idle"\n}}\n')
    for identity in country_families():
        tag = identity.split("_", 1)[0]
        if tag not in DESIGNS:
            continue
        for kind in CLASSES:
            routes = [f"{kind}_armor{tier}" for tier in ("", "_0", "_1", "_2", "_3", "_4")]
            for route in (*routes, *TANK_SUBUNITS[kind], *TANK_EQUIPMENT[kind]):
                assets += alias(f"ADISCORD_{model_name(tag, kind)}_entity", f"{identity}_{route}_entity")
    return gfx, assets, animations


def registry():
    gfx = HEADER + "objectTypes = {\n"
    assets = HEADER
    animations = HEADER
    for name in NAMES + SHARED_NAMES + SPECIAL_NAMES:
        tank = name.endswith("_tank") or name == "STS_taran"
        clips = ("idle", "move", "attack") if tank else ("idle",)
        gfx += f'\tpdxmesh = {{\n\t\tname = "ADISCORD_{name}_mesh"\n'
        gfx += f'\t\tfile = "gfx/models/units/ADISCORD_country_vehicles/{name}.mesh"\n'
        scale = 0.50 if name == "STS_taran" else 0.55 if tank else 1.0
        gfx += f'\t\tscale = {scale}\n'
        if name.endswith("_tank") and name.split("_")[0] in DESIGNS:
            tag = name.split("_")[0]
            gfx += (f'\t\tmeshsettings = {{\n\t\t\tname = "{name}"\n\t\t\tindex = 0\n'
                    f'\t\t\ttexture_diffuse = "{tag}_medium_armor_diffuse.dds"\n'
                    f'\t\t\ttexture_normal = "{name}_normal.dds"\n'
                    f'\t\t\ttexture_specular = "{name}_specular.dds"\n'
                    '\t\t\tshader = "PdxMeshAdvanced"\n\t\t}\n')
        for clip in clips:
            gfx += f'\t\tanimation = {{ id = "{clip}" type = "ADISCORD_{name}_{clip}_animation" }}\n'
            animations += f'animation = {{ name = "ADISCORD_{name}_{clip}_animation" file = "{name}_{clip}.anim" }}\n'
        gfx += "\t}\n"
        parent = "medium_armor_entity" if tank else "light_plane_entity"
        assets += f'\nentity = {{\n\tclone = "{parent}"\n\tname = "ADISCORD_{name}_entity"\n'
        assets += f'\tpdxmesh = "ADISCORD_{name}_mesh"\n\tdefault_state = "idle"\n'
        if not tank:
            assets += "\tscale = 0.20\n"
        assets += "}\n"
    apc_gfx, apc_assets, apc_animations = apc_registry()
    tank_gfx, tank_assets, tank_animations = tank_registry()
    gfx += apc_gfx + tank_gfx + "}\n"
    assets += apc_assets + artillery_entities() + tank_assets
    animations += apc_animations + tank_animations
    routes = air_routes()
    assets += "\n"
    for name, (role, tier) in routes.items():
        assets += alias(f"ADISCORD_DEF_{PREFIXES[tier]}{role}_entity", f"{name}_entity")
    for tag, family in country_families().items():
        assets += "\n"
        for name, (role, tier) in routes.items():
            assets += alias(f"ADISCORD_{family}_{PREFIXES[tier]}{role}_entity", f"{tag}_{name}_entity")
        # Native carrier and medium-aircraft sprites share the country's design language.
        for sprite, role in (("light_plane", "fighter"), ("medium_plane", "cas")):
            assets += alias(f"ADISCORD_{family}_early_{role}_entity", f"{tag}_{sprite}_entity")
            for level in range(4):
                prefix = PREFIXES[min(level, 2)]
                assets += alias(f"ADISCORD_{family}_{prefix}{role}_entity", f"{tag}_{sprite}_{level}_entity")
    assets += "\n"
    for prefix in ("", "STS_", "STS_steland_", "STS_hegemony_"):
        for name in ("STP_taran", "STP_taran_0", "STP_taran_equipment", "STP_taran_equipment_1"):
            assets += alias("ADISCORD_STS_taran_entity", f"{prefix}{name}_entity")
    return gfx, assets, animations


def package(apply=False):
    gfx, assets, animations = registry()
    files = {
        MOD / "gfx/entities/ADISCORD_country_vehicles.gfx": gfx.encode(),
        MOD / "gfx/entities/zz_ADISCORD_country_vehicles.asset": assets.encode(),
        MOD / "gfx/interface/equipmentdesigner/graphic_db/ADISCORD_country_tanks.txt": tank_pool_registry().encode(),
        DEST / "animation.asset": animations.encode(),
        MOD / "gfx/interface/equipmentdesigner/graphic_db/ADISCORD_country_vehicles.txt": apc_model_pools().encode(),
    }
    changed = [str(path.relative_to(MOD)) for path, data in files.items()
               if not path.is_file() or path.read_bytes() != data]
    if apply:
        for path, data in files.items():
            if str(path.relative_to(MOD)) in changed:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    return changed


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true")
    action.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    changed = package(args.apply)
    print(json.dumps({"changed": changed, "applied": args.apply}, indent=2))
    if args.check and changed:
        raise SystemExit(1)
